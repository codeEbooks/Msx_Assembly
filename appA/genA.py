#!/usr/bin/env python3
"""genA.py - the programs of Appendix A: every documented instruction, timed
and run.

    python3 genA.py && ./build.sh

    times.asm   each of the 698 instructions of iset.py, run once between
                two labels, t and e: the jumps on a condition twice, once
                jumping and once not, the RSTs twice, the block instructions
                that repeat for three turns (CPIR and CPDR also until they
                find the byte). The pointer registers point into the RAM and
                fix puts them back after each instruction; C is the VDP's
                data port, with the display off, as in chapter 14. At the
                end, HALT and the interrupt's answer: four HALTs started a
                few turns before the VDP's signal, two in mode 2, one in
                mode 1, one in mode 0. measA.py stops at every label.
    flags.asm   each instruction run again and again from a table, with eight
                values of F and the registers and memory of each
                state of its group: the operands that make every flag both 0
                and 1 where it can. After each run the debugger reads every
                register, the shadow ones too, and the bytes the instruction
                may have written (measA.py). HALT, which waits for an
                interrupt, and RST, which jumps into the BIOS, are timed in
                times.asm and their F read there. A cartridge of 32 KB: the
                table needs more than 16.

build.sh assembles with --syntax=bFw (chapter 15).
"""
