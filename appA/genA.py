def head(name, what):
    return f"""; {name}.asm -- appendix A: {what}
; generated by genA.py
        INCLUDE "msx.inc"
        OUTPUT "{name}.rom"
        ORG $4000
        CART_HEADER init
VARS    EQU RAM_START + $100    ; the program's variables: the code is in ROM
"""


# ------------------------------------------------------------------ times.asm
PTR = {"bc": 0xC098, "de": 0xC100, "hl": 0xC200, "ix": 0xC300, "iy": 0xC400}   # chapter 14's
NN = 0xC500                 # the address in the instructions that carry one
D = 5                       # the distance in (IX+d) and (IY+d)
N = 0x5A                    # the number in the instructions that carry one
PORT = 0x98                 # and in IN A,(n) and OUT (n),A: the VDP's data port
TOP = 0xF37E                # the stack: SYS_AREA - 2, as in chapter 14
RSTK = 0xE100               # the stack of the RSTs: SP is RSTK - 2 in the BIOS
ISTK = 0xE200               # the stack of the timed HALTs: ISTK - 2 at $0038
SSTK = 0xE300               # and of the HALTs that wait for the frame
CP_BYTES = (0x11, 0x22, 0x33)   # what CPIR and CPDR look through
CP_FIND, CP_MISS = 0x22, 0x99   # a byte that is there, the second, and one that is not
TURNS = 3                   # BC or B for the instructions that repeat
TRUE_F = {"NZ": 0x00, "Z": 0xFF, "NC": 0x00, "C": 0xFF,     # an F that makes cc hold
          "PO": 0x00, "PE": 0xFF, "P": 0x00, "M": 0xFF}
# the HALTs: the mode, and about how many turns each should wait; measA.py
# reads the true number from R
HALT_TURNS = [(2, 10), (2, 20), (1, 10), (0, 10)]
HALT_F = [0x00, 0xFF, 0x00, 0xFF]   # F before each
FRAME_T = 71364             # a frame of the 50 Hz machine (tools/meas.py)
WAIT_TURN = 30              # a turn of the wait: DEC BC, LD A,B, OR C, JR NZ


def asm_of(r, target, n=None, nn=NN):
    return r["asm"].format(n=f"${(n if n is not None else (PORT if r['family'] == 'ports' else N)):02X}",
                           nn=f"${nn:04X}", d=D, t=target)


def set_f(f):
    return [f"ld hl,${f:04X}", "push hl", "pop af            ; F", "call fix"]


def cases():
    """every timed case: (row, what, setup lines, rst)"""
    out = []
    for r in iset.rows():
        op = r["key"][-1]
        if r["kind"] == "halt":
            continue
        if r["kind"] == "cond" and r["cc"] == "B":              # DJNZ
            out += [(r, "taken", ["ld b,2"], None), (r, "not", ["ld b,1"], None)]
        elif r["kind"] == "cond":
            ret = op & 0xC7 == 0xC0
            for what in ("taken", "not"):
                f = TRUE_F[r["cc"]] if what == "taken" else TRUE_F[r["cc"]] ^ 0xFF
                out.append((r, what, (["ret_to"] if ret else []) + set_f(f), None))
        elif r["text"].startswith("RST"):
            for f in (0x00, 0xFF):
                out.append((r, f"F{f:02X}", set_f(f) + [f"ld sp,${RSTK:04X}"],
                            8 * ((op >> 3) & 7)))
        elif r["text"] in ("RET", "RETI", "RETN"):
            out.append((r, "", ["ret_to"], None))
        elif r["text"].startswith("JP ("):
            reg = r["text"][4:6].lower()
            out.append((r, "", [f"ld {reg},TARGET"], None))
        elif r["kind"] == "repeat" and r["text"] in ("CPIR", "CPDR"):
            step = 1 if r["text"] == "CPIR" else -1
            fill = []
            for k, b in enumerate(CP_BYTES):
                fill += [f"ld a,${b:02X}", f"ld (${PTR['hl'] + step * k:04X}),a"]
            for what, a in (("found", CP_FIND), ("runout", CP_MISS)):
                out.append((r, what, fill + [f"ld bc,{TURNS}", f"ld a,${a:02X}"], None))
        elif r["kind"] == "repeat":
            reg = "b" if r["key"][1] & 3 >= 2 else "bc"
            out.append((r, "turns", [f"ld {reg},{TURNS}"], None))
        else:
            out.append((r, "", [], None))
    return out


def times():
    lines, cs = [], cases()
    for c, (r, what, setup, rst) in enumerate(cs, start=1):
        lines.append(f"; {r['n']} {r['text']}" + (f", {what}" if what else ""))
        for s in setup:
            if s == "ret_to":
                lines += [f"        ld hl,e{c}", "        push hl                 ; where it returns to"]
            else:
                lines.append("        " + s.replace("TARGET", f"e{c}"))
        body = asm_of(r, f"e{c}").split("\n")
        lines.append(f"{f't{c}:':<8}{body[0].strip()}")
        lines += ["        " + b.strip() for b in body[1:]]
        lines.append(f"{f'e{c}:':<8}" + ("di" if r["text"] == "EI" else "ld sp,TOP"))
        if r["text"] == "EI":
            lines.append("        ld sp,TOP")
        lines.append("        call fix")
    halts = [halt_test(k, im, turns) for k, (im, turns) in enumerate(HALT_TURNS, start=1)]
    return head("times", "every documented instruction, timed") + IM2 + f"""
; Every documented instruction, once, between two labels: t before it and e
; after it, where every jump goes. The pointer registers point into the RAM,
; and fix puts them back after each; C is the VDP's data port, with the
; display off, as in chapter 14. At the end, HALT and the interrupt's
; answer in the three modes.
PTR_BC  equ ${PTR['bc']:04X}
PTR_DE  equ ${PTR['de']:04X}
PTR_HL  equ ${PTR['hl']:04X}
PTR_IX  equ ${PTR['ix']:04X}
PTR_IY  equ ${PTR['iy']:04X}
TOP     equ ${TOP:04X}               ; the stack, as in chapter 14

init:   di
        ld sp,TOP
        VDP_REG 1, $80          ; display off, no signal from the VDP
        call fix
""" + "\n".join(lines) + f"""
; HALT and the interrupt's answer
        ld sp,TOP
""" + im2("isr") + """        VDP_REG 1, $A0          ; the VDP's signal on, the display off
""" + "".join(halts) + f"""done:   jr done

; fix: the pointer registers back where they belong
fix:    ld bc,PTR_BC
        ld de,PTR_DE
        ld hl,PTR_HL
        ld ix,PTR_IX
        ld iy,PTR_IY
        ret

; isr: mode 2's routine: the VDP takes its signal down; back, interrupts off
isr:    in a,(VDP_CTRL)
        ret
        ASSERT $ <= $8000, the program is longer than the cartridge
        ds $8000 - $, $FF       ; pad the cartridge to 16 KB
"""


def halt_test(k, im, turns):
    """HALT number K, in mode IM, started about TURNS turns of 5 T-states
    before the VDP's next signal: after a HALT in mode 2 that waits for the
    signal, a wait of the right length, and F set to HALT_F[K - 1]"""
    # from the answer to the signal before: the answer (19), the JP at the
    # vector (11), IN (12), RET (11), IM (10, but not in mode 2), LD BC,nn
    # (11), the wait's turns less 5 for the last JR, LD SP,nn (11), LD HL,nn,
    # PUSH HL and POP AF (11, 12, 11), EI (5); then the HALT's turns, to the
    # next signal a frame on
    fixed = 19 + 11 + 12 + 11 + (0 if im == 2 else 10) + 11 - 5 + 11 + 11 + 12 + 11 + 5
    count = (FRAME_T - fixed - 5 * turns) // WAIT_TURN
    mode = "" if im == 2 else f"        im {im}\n"
    return (f"; HALT {k}: mode {im}, about {turns} turns before the VDP's signal\n"
            f"        ld sp,${SSTK:04X}\n"
            "        im 2\n"
            "        in a,(VDP_CTRL)         ; no signal left over\n"
            "        ei\n"
            "        halt                    ; the signal: the frame starts again\n"
            + mode +
            f"        ld bc,{count}\n"
            f"w{k}:     dec bc\n"
            "        ld a,b\n"
            "        or c\n"
            f"        jr nz,w{k}\n"
            f"        ld sp,${ISTK:04X}\n"
            f"        ld hl,${HALT_F[k - 1]:04X}\n"
            "        push hl\n"
            "        pop af                  ; F\n"
            f"{f'h{k}:':<8}ei\n"
            "        halt                    ; the HALT timed\n"
            "        di\n"
            "        in a,(VDP_CTRL)         ; the VDP's signal down\n")


