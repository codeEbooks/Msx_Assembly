def group_of(r):
    """the group of states a row runs with"""
    fam, form, text = r["family"], r["form"], r["text"]
    if fam == "load8":
        return "P"
    if fam == "load16":
        return "PF"
    if fam in ("arith8", "logic"):
        if text in ("NEG", "CPL", "SCF", "CCF"):
            return "ACC"
        if text == "DAA":
            return "DAA"
        if form.startswith(("INC", "DEC")):
            return "INCM" if "(" in form else "INC"
        return "A8M" if "(" in form else "A8R"
    if fam == "arith16":
        return "INC16" if form.startswith(("INC", "DEC")) else "R16"
    if fam == "rot":
        if text in ("RLCA", "RRCA", "RLA", "RRA"):
            return "ACC"
        if text in ("RLD", "RRD"):
            return "RD"
        return "ROTM" if "(" in form else "ROT"
    if fam == "bits":
        return "BITM" if "(" in form else "BIT"
    if fam == "jumps":
        if text in ("RET", "RETI", "RETN") or form == "RET cc":
            return "PR"
        if text.startswith("JP ("):
            return "PJ"
        if text == "DJNZ e":
            return "PB"
        return "P"
    if fam == "block":
        return {"LDIR": "LDI", "LDDR": "LDD", "CPIR": "CPI", "CPDR": "CPD"}.get(text, text)
    if fam == "ports":
        return "INR" if text.startswith("IN") else "OUTR"
    if fam == "control":
        return "P"
    raise ValueError(r)


def variants(r):
    """[(lines before, the instruction, group)]: one for most rows"""
    if r["text"] == "LD A,I":
        return ([([f"ld a,${i:02X}", "ld i,a"], "ld a,i", "P") for i in (0x00, 0x7F, 0x80)]
                + [(["ld a,$C3", "ld i,a", "ei"], "ld a,i", "P")])
    if r["text"] == "LD A,R":
        return ([([f"ld a,${v:02X}", "ld r,a"], "ld a,r", "P") for v in (0x7E, 0xFE, 0x10)]
                + [(["ld a,$40", "ld r,a", "ei"], "ld a,r", "P")])
    if r["kind"] == "halt" or r["text"].startswith("RST"):
        return []
    if r["family"] in ("arith8", "logic") and r["form"].endswith("n"):
        return [([], asm_of(r, "TARGET", v, M), "ACC") for v in NVALS]
    if r["family"] == "ports" and "(n)" in r["text"]:
        n = IN_PORT if r["text"].startswith("IN") else OUT_PORT
        return [([], asm_of(r, "TARGET", n, M), group_of(r))]
    return [([], asm_of(r, "TARGET", N, M), group_of(r))]


def flag_runs():
    """[(row, block label, lines before, the instruction, group)] in table order"""
    out, v = [], 0
    for r in iset.rows():
        for pre, ins, g in variants(r):
            v += 1
            out.append((r, f"b{v}", pre, ins, g))
    return out


def word(x):
    return x if isinstance(x, str) else f"${x:04X}"


def state_lines(label, s):
    regs = [word(s["a"] << 8), word(s["bc"]), word(s["de"]), word(s["hl"]), word(s["ix"]),
            word(s["iy"])]
    return [f"{label + ':':<8}dw {','.join(regs)}",
            f"        dw {word(s['sp'])},{word(s['spw'])},{word(s['af2'])}",
            f"        db ${s['psg']:02X}",
            "        db " + ",".join(f"${b:02X}" for b in s["win"])]


def flags():
    runs = flag_runs()
    g = groups()
    used = sorted({x[4] for x in runs}, key=list(g).index)
    blocks = []
    for r, lab, pre, ins, grp in runs:
        blocks.append(f"; {r['n']} {r['text']}")
        body = list(pre)
        if "TARGET" in ins and ins.startswith(("jr", "djnz")):
            body += ins.replace("TARGET", f"a{lab[1:]}").split("\n")
            body.append(f"a{lab[1:]}:")
        else:
            body += ins.replace("TARGET", "after").split("\n")
        first = True
        for b in body:
            b = b.strip()
            if b.endswith(":") and " " not in b:
                blocks.append(f"{b:<8}jp after")
                first = None
                break
            blocks.append(f"{(lab + ':') if first else '':<8}{b}")
            first = False
        if first is not None:
            blocks.append("        jp after")
    itab = [f"        dw {lab},g_{grp}" for r, lab, pre, ins, grp in runs] + ["        dw 0"]
    gtab, stab, k = [], [], 0
    for name in used:
        labels = []
        for s in g[name]:
            k += 1
            labels.append(f"s{k}")
            stab += state_lines(f"s{k}", s)
        gtab.append(f"{f'g_{name}:':<8}db {len(labels)}")
        for j in range(0, len(labels), 8):
            gtab.append("        dw " + ",".join(labels[j:j + 8]))
