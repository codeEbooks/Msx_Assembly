#!/usr/bin/env python3
"""genI.py -- writes the sources of Appendix I, the Workshops' answers.

Run it, then build.sh; measI.py measures what they do.

    python3 genI.py && ./build.sh

  prices     every instruction an answer prices, alone between two labels,
             p_name before it and q_name after it, with what it needs first
             and what puts the machine back after: measI.py reads the time
             and R at both labels
  flags      chapter 2, question 4: 100 + 100 and 200 - 100, A and F kept
  bit4100    chapter 1, question 1: $FF written at byte 4,100 of the
             pattern table of chapter 1's Graphic II
  clash120   chapter 1, question 2: chapter 1's clash_ball with the ball at
             x = 120 instead of 124
  y208_0     chapter 1, question 3: chapter 1's five sprites, sprite 0 at
             Y = 208
  beam_244   chapter 1, question 5: chapter 1's stripe 244 T-states later
  solutions  the code the answers print: the answers' own (9.4, 15.2, 16.3),
             run once with inputs known, and the code six answers took from
             the chapters' programs, as those programs have it

The chapter 1 programs are made by gen01.py's own functions, so that they are
chapter 1's code with one thing changed; the chapters' pieces are cut from the
programs that measured them, so that the listing is the code that ran.
"""
import ast
import importlib.util
import inspect
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
sys.path.insert(0, str(REPO / "tools"))
sys.dont_write_bytecode = True


def chapter_module(folder, name):
    """a program of a chapter's folder, imported as a module, with that folder
    first on the path (its own imports are its neighbours)"""
    if name in sys.modules:
        return sys.modules[name]
    path = REPO / folder
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))
    spec = importlib.util.spec_from_file_location(name, path / f"{name}.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


HEAD = '''; {name}.asm -- appendix I: {what}
; generated by genI.py
        INCLUDE "msx.inc"
        OUTPUT "{name}.rom"
        ORG $4000
        CART_HEADER init
'''
TAIL = '''        ds $8000 - $, $FF       ; pad the cartridge to 16 KB
        ASSERT $ == $8000
'''
QUIET = '''init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $80          ; display off, no frame interrupt
        in a, (VDP_CTRL)        ; and none waiting
'''


def write(name, text):
    (HERE / f"{name}.asm").write_text(text)


