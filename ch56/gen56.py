#!/usr/bin/env python3
"""gen56.py - the sources of chapter 56: releasing the two games.

    python3 gen56.py && ./build.sh

    grin_alley.asm, grin_music.inc
                GRIN ALLEY as chapter 44 finished it: chapter 44's own
                generator writes the source, and only the names of the
                cartridge's file and of the tune's change
    lantern_keep.asm, keep_music.inc
                LANTERN KEEP as chapter 54 left it, with its title and its
                demo, the same way
    label.asm   the words of the cartridges' labels, written on a page in
                Graphic I with the BIOS's own character set, white on black,
                to be photographed: every pixel of a label is one openMSX drew

build.sh assembles the three with --syntax=bFw, and then pack56.py makes the
files of the release from the two cartridges: the images for an EPROM and the
text that goes with each game. A release cartridge must be the book's, byte
for byte: meas56.py holds them against chapter 44's and chapter 54's.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
for ch in ("tools", "ch26", "ch51"):
    sys.path.insert(0, os.path.join(REPO, ch))
from asmparts import TEXT_PAGE, CART_END, library  # noqa: E402
from gen26 import tidy  # noqa: E402  (chapter 26)
import gen51  # noqa: E402  (chapter 51: the header of a program with its variables at $E000)

# the two games: the chapter whose generator writes each, and its names here
GAMES = {
    "grin_alley": {"chapter": 44, "music": "grin_music.inc", "title": "GRIN ALLEY", "kb": 16},
    "lantern_keep": {"chapter": 54, "music": "keep_music.inc", "title": "LANTERN KEEP", "kb": 32},
}

# the label's words: (row, column, text) on the page label.asm draws
WORDS = {
    "lantern_keep": (2, 2, "LANTERN KEEP"),
    "grin_alley": (4, 2, "GRIN ALLEY"),
    "cartridge": (6, 2, "MSX1 CARTRIDGE"),
    "kb32": (8, 2, "32 KB ROM"),
    "kb16": (10, 2, "16 KB ROM"),
    "maker": (12, 2, "CODE & BOOKS 2026"),
}
for _r, _c, _s in WORDS.values():
    assert _c + len(_s) <= 31


def chapter_source(chapter):
    """the game's source and its tune, as the chapter's own generator writes
    them, asked in a process of its own so that the two chapters' modules,
    which share names, never meet"""
    code = (f"import sys, json; sys.path.insert(0, {os.path.join(REPO, f'ch{chapter}')!r}); "
            f"import gen{chapter} as g; print(json.dumps([g.program('game'), g.music_inc()]))")
    out = subprocess.run([sys.executable, "-c", code], capture_output=True, text=True, check=True,
                         cwd=os.path.join(REPO, f"ch{chapter}")).stdout
    import json
    return json.loads(out.splitlines()[-1])


def game(name):
    """the release's source: the chapter's, with its own file names"""
    g = GAMES[name]
    asm, music = chapter_source(g["chapter"])
    for old, new in (('        OUTPUT "game.rom"\n', f'        OUTPUT "{name}.rom"\n'),
                     ('        INCLUDE "music.inc"\n', f'        INCLUDE "{g["music"]}"\n')):
        assert asm.count(old) == 1, (name, old)
        asm = asm.replace(old, new)
    first, second = asm.splitlines()[:2]
    assert first.startswith("; game.asm -- chapter") and second == f"; generated by gen{g['chapter']}.py"
    asm = asm.replace(first + "\n" + second + "\n",
                      f"; {name}.asm -- chapter 56: the release of {g['title']}, chapter "
                      f"{g['chapter']}'s game.asm\n; generated by gen56.py with chapter "
                      f"{g['chapter']}'s gen{g['chapter']}.py\n", 1)
    return asm, music


# the label's page: chapter 51's page in Graphic I, white on black
def label():
    page = (TEXT_PAGE.replace("        VDP_REG 7, $0F          ; border white\n",
                              "        VDP_REG 7, $01          ; border black\n")
            .replace("        VRAM_WRITE $2000        ; colours: black ink (1) on white paper (15)\n"
                     "        ld b, 32\n        ld a, $1F\n",
                     "        VRAM_WRITE $2000        ; colours: white ink (15) on black paper (1)\n"
                     "        ld b, 32\n        ld a, $F1\n"))
    assert page.count("$01          ; border black") == 1 and page.count("ld a, $F1") == 1
    body = page + "".join(f"""        ld b, {r}
        ld c, {c}
        ld hl, w_{k}
        call puts
""" for k, (r, c, _) in WORDS.items()) + """        VDP_REG 1, $C0          ; display on
done:   jr done
""" + library() + "".join(f'w_{k}: db "{s}", 0\n' for k, (_, _, s) in WORDS.items())
    head = gen51.head("label", "the words of the labels").replace(
        "chapter 51:", "chapter 56:").replace("generated by gen51.py", "generated by gen56.py")
    return (head + '        INCLUDE "bios.inc"\n'
            "; The words of the two labels, white on black, to be photographed.\n"
            + tidy(body) + CART_END)


def main():
    written = []
    for name, g in GAMES.items():
        asm, music = game(name)
        for fname, text in ((f"{name}.asm", asm), (g["music"], music)):
            with open(os.path.join(HERE, fname), "w") as f:
                f.write(text)
            written.append(fname)
    with open(os.path.join(HERE, "label.asm"), "w") as f:
        f.write(label())
    written.append("label.asm")
    print(" ".join(written))


if __name__ == "__main__":
    main()
