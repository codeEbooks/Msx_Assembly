def head(name, what, size_kb=16):
    return f"""; {name}.asm -- appendix C: {what}
; generated by genC.py
        INCLUDE "msx.inc"
        OUTPUT "{name}.rom"
        ORG $4000
        CART_HEADER init
"""


def tail(size_kb=16):
    end = 0x4000 + size_kb * 1024
    return f"""
        ASSERT $ <= ${end:04X}, the program is longer than the cartridge
        ds ${end:04X} - $, $FF       ; pad the cartridge to {size_kb} KB
"""


STACK = 0xF370                  # SP: below the BIOS's work area
SLOT_TEST = 1                   # the cartridge's slot on the book's machines


def vram_write(addr):
    return [f"ld a,${addr & 0xFF:02X}", "out (VDP_CTRL),a",
            f"ld a,${addr >> 8 | 0x40:02X}", f"out (VDP_CTRL),a       ; write from ${addr:04X}"]


def vram_read(addr):
    return [f"ld a,${addr & 0xFF:02X}", "out (VDP_CTRL),a",
            f"ld a,${addr >> 8:02X}", f"out (VDP_CTRL),a       ; read from ${addr:04X}"]


def vdp_reg(r, v, why=""):
    return [f"ld a,${v:02X}", "out (VDP_CTRL),a",
            f"ld a,${0x80 | r:02X}", f"out (VDP_CTRL),a       ; R#{r} = ${v:02X}{why}"]


def psg(r, v, why=""):
    return [f"ld a,{r}", "out (PSG_ADDR),a", f"ld a,${v:02X}",
            f"out (PSG_WRITE),a      ; register {r} = ${v:02X}{why}"]


def code(lines, label=None):
    """lines of code at column 8; LABEL on the first"""
    out = []
    for k, l in enumerate(lines):
        if l.startswith(";") or l.endswith(":") or re.match(r"\w+: ", l):
            out.append(l)                       # a comment, or a label of its own
        else:
            out.append(("" if k or not label else label + ":") + "        " + l)
    return "\n".join(out)


CLEAR_VRAM = """
; clear: VRAM all 0, from $0000; uses A, B, C
clear:  xor a
        out (VDP_CTRL),a
        ld a,$40
        out (VDP_CTRL),a        ; write from $0000
        ld bc,$4000
clr:    xor a
        out (VDP_DATA),a
        dec bc
        ld a,b
        or c
        jr nz,clr
        ret
"""


# ------------------------------------------------------------------ ports.asm
TEST_VRAM = 0x3000              # where port $98 reads, after a read address
S1 = dict(vram=0x5A, psg=0x5A, c=0x50)      # the two states of the reads: VRAM
S2 = dict(vram=0xA5, psg=0xA5, c=0x58)      # at TEST_VRAM, register 5, port C
PSG_TEST = 5                    # a register of the PSG that keeps 8 bits
SPACE = (8, 0x01)               # the key held in state 2: SPACE, row 8 bit 0
W_ADDR = 0x1000                 # where the data port writes in passes 1 and 2
W_CTRL = 0x0515                 # where the control port's $15, $45 point
VALUES = (0x15, 0x45, 0x05, 0x04)   # all keep bits 3 and 2 at 0 1, bit 7 at 0
for v in VALUES:
    assert v & 0x8C == 0x04
PRN_BYTE = 0x50                 # what the printer prints in pass 9: "P"
SETTLE = 10                     # turns of a wait after the OUTs, 16 T-states
                                # each: the VDP writes the VRAM a little later

READS = [("r1", S1, 0x00, "state 1"), ("r3", S1, 0xFF, "state 1, B = $FF"),
         ("r2", S2, 0x00, "state 2: SPACE held, the printer plugged in")]

# the write passes: name, what it finds, set-up, the OUT(s) to port C, after
PRE_VDP = (["in a,(VDP_CTRL)        ; the latch cleared"] + vram_write(W_CTRL) +
           ["xor a", f"out (VDP_DATA),a       ; ${W_CTRL:04X} = 0"] + vram_write(W_ADDR) +
           ["xor a", "out (VDP_DATA),a", "out (VDP_DATA),a",
            f"out (VDP_DATA),a       ; ${W_ADDR:04X} to ${W_ADDR + 2:04X} = 0"] + vram_write(W_ADDR))
WRITES = [
    ("w1", "the VDP's data port", PRE_VDP, [0x15], []),
    ("w2", "the VDP's control port", PRE_VDP, [0x15, 0x45],
     ["ld a,$55", f"out (VDP_DATA),a       ; $55 where the address is"]),
    ("w3", "the PSG's register select",
     psg(0, 0) + psg(PSG_TEST, 0) + ["xor a", "out (PSG_ADDR),a       ; register 0 chosen"],
     [0x05], ["ld a,$15", "out (PSG_WRITE),a      ; $15 to the register chosen"]),
    ("w4", "the PSG's data port", psg(PSG_TEST, 0, ", and chosen"), [0x15], []),
    ("w5", "the PPI's port A", [], [0x15], []),
    ("w6", "the PPI's port C", ["ld a,$F0", "out (PPI_C),a          ; port C = $F0"], [0x15], []),
    ("w7", "the PPI's control port", ["ld a,$F0", "out (PPI_C),a          ; port C = $F0"],
     [0x05], []),
    ("w8", "the printer's data", ["xor a", "out ($91),a            ; the printer's data = 0"],
     [0x15], []),
    ("w9", "the printer's strobe",
     [f"ld a,${PRN_BYTE:02X}", "out ($91),a            ; the printer's data",
      "ld a,$05", "out ($90),a            ; the strobe at 1: a byte printed if it was 0"],
     [0x04], []),
]


def ports():
    say = f"""
; Every port read, in two states and with two high bytes, then written, in
; nine passes. measC.py reads the tables of reads at r1done, r3done and
; r2done, and the VDP, the PSG, the PPI and the printer at each probe.
TAB     EQU RAM_START           ; the reads: r1, r3, r2, 256 bytes each

init:   di
        ld sp,${STACK:04X}
        in a,(PPI_A)
        ld e,a                  ; E: the slots, put back after every OUT
""" + code(vdp_reg(1, 0x80, ": 16 KB, the screen off") + ["call clear"]) + "\n"
    body = []
    for k, (name, s, b, what) in enumerate(READS):
        body.append(f"\n; {name}: every port read, {what}")
        pre = vram_write(TEST_VRAM) + ["ld a,$%02X" % s["vram"],
                                       f"out (VDP_DATA),a       ; ${TEST_VRAM:04X} = ${s['vram']:02X}"]
        pre += psg(PSG_TEST, s["psg"])
        if name == "r2":
            body.append(code(["nop                    ; measC.py: SPACE held, printer in"],
                             label="state2"))
        body.append(code(pre + [f"ld hl,TAB+${k * 256:03X}", "ld c,0", f"ld b,${b:02X}"]))
        loop = (["in a,(VDP_CTRL)        ; the latch and F cleared"] + vram_read(TEST_VRAM) +
                [f"ld a,{PSG_TEST}", f"out (PSG_ADDR),a       ; register {PSG_TEST} chosen",
                 "ld a,$%02X" % s["c"], f"out (PPI_C),a          ; port C = ${s['c']:02X}",
                 "in a,(c)               ; the port", "ld (hl),a", "inc hl", "inc c",
                 f"jr nz,{name}loop"])
        body.append(code(loop, label=f"{name}loop"))
        body.append(code(["nop                    ; measC.py reads the table"], label=f"{name}done"))
    for name, what, pre, outs, post in WRITES:
        body.append(f"\n; {name}: every port written, for {what}")
        body.append(code(["ld bc,0                ; port 0, B = 0"]))
        lines = list(pre)
        for v in outs:
            lines += [f"ld a,${v:02X}", "out (c),a              ; the port"]
        lines += post
        lines += [f"ld d,{SETTLE}", f"wait{name}: dec d", f"jr nz,wait{name}"]
        body.append(code(lines, label=f"{name}loop"))
        body.append(code(["ld a,e", "out (PPI_A),a          ; the slots back",
                          "inc c", f"jr nz,{name}loop"], label=f"{name}probe"))
    body.append(code(["jr done"], label="done"))
    return (head("ports", "every port, read and written") + say + "\n".join(body) + "\n" +
            CLEAR_VRAM + tail())


# ------------------------------------------------------------------ vdp.asm
BASE_REGS = [0x00, 0x80, 0x06, 0x80, 0x00, 0x36, 0x07, 0xF4]   # Graphic I, the screen
                                # off: names $1800, colours $2000, patterns $0000,
                                # sprites $1B00 and $3800, as the BIOS's SCREEN 1
RES = 0xC000                    # where the program keeps what IN gave: 8 bytes
MARKS = [0x0000, 0x0001, 0x003F, 0x0040, 0x0041, 0x007F, 0x0080, 0x00FF, 0x0100,
         0x0FFF, 0x1000, 0x1FFF, 0x2000, 0x3FFF]    # written in the 4 KB mode
PREFETCH = 0x2000               # $11 $22 $33 $44 here
AFTER_W = 0x2100                # $55 $66 $77 here
SPRITES = [(100, 0), (100, 0), (100, 40), (100, 60), (100, 80)]    # Y, X: 5 on a
                                # line, the first two on the same columns
WAIT_TURNS = 11894              # 30 T-states a turn: five frames of 71,364
IE_REGS = (0xE0, 0xC0)          # R#1 with IE on and off, the screen on


def local_labels(name, lines):
    """each label written X@ made the case's own: the n-th X@ defined in the
    case, and the jumps to X@ that follow it, become X<name>_<n>"""
    out, n = [], {}
    for l in lines:
        m = re.match(r"(\w+)@:", l)
        if m:
            n[m.group(1)] = n.get(m.group(1), 0) + 1
        out.append(re.sub(r"(\w+)@", lambda k: f"{k.group(1)}{name}_{n.get(k.group(1), 0)}", l))
    return out


def settle():
    return ["ld d,10", "wait@: dec d", "jr nz,wait@"]


def probe_label(name):
    return [f"v{name}: nop                ; measC.py reads the VDP"]


def wait_frames():
    return [f"ld bc,{WAIT_TURNS}", "spin@: dec bc", "ld a,b", "or c", "jr nz,spin@"]


HIGH_NUMS = [0x97, 0xA3, 0xB5, 0xF6]    # second bytes with bits 4 and 5 of the number set


def vdp_cases():
    """[(name, lines)]: each case's code, then the probe v<name>"""
    cases = []
    base = []
    for r, v in enumerate(BASE_REGS):
        base += vdp_reg(r, v)
    cases.append(("base", base + ["call clear"]))
    for r in range(8):                                  # what each register keeps
        cases.append((f"keep{r}ff", vdp_reg(r, 0xFF)))
        cases.append((f"keep{r}00", vdp_reg(r, 0x00)))
        cases.append((f"back{r}", vdp_reg(r, BASE_REGS[r])))
    zero = []
    for r in range(8):
        zero += vdp_reg(r, 0x00)
    for n in list(range(8, 16)):                        # register numbers 8 to 15
        cases.append((f"num{n}", zero + ["ld a,$FF", "out (VDP_CTRL),a",
                                         f"ld a,${0x80 | n:02X}", "out (VDP_CTRL),a       ; R#" +
                                         f"{n}?"]))
    for v in HIGH_NUMS:                                 # bits 4 and 5 of the number too
        cases.append((f"high{v:02X}", zero + ["ld a,$FF", "out (VDP_CTRL),a",
                                              f"ld a,${v:02X}", "out (VDP_CTRL),a       ; R#" +
                                              f"{v & 0x3F}?"]))
    for n in range(8):                                  # bit 6 of the second byte set
        cases.append((f"bit6_{n}", zero + ["ld a,$FF", "out (VDP_CTRL),a",
                                           f"ld a,${0xC0 | n:02X}",
                                           "out (VDP_CTRL),a       ; bits 7 and 6 set"]))
    back = []
    for r, v in enumerate(BASE_REGS):
        back += vdp_reg(r, v)
    cases.append(("restored", back))
    cases.append(("first", ["in a,(VDP_CTRL)        ; the latch cleared", "ld a,$34",
                            "out (VDP_CTRL),a       ; a first byte alone"]))
    cases.append(("second", ["ld a,$52", "out (VDP_CTRL),a       ; and the second: write, $1234"]))
    cases.append(("cleared1", ["ld a,$78", "out (VDP_CTRL),a       ; a first byte",
                               "in a,(VDP_CTRL)        ; the status read"]))
    cases.append(("cleared2", ["ld a,$56", "out (VDP_CTRL),a       ; a first byte again?"]))
    cases.append(("cleared3", ["ld a,$5A", "out (VDP_CTRL),a       ; write, $1A56?"]))
    cases.append(("bydata1", ["in a,(VDP_CTRL)", "ld a,$78", "out (VDP_CTRL),a       ; a first byte",
                              "in a,(VDP_DATA)        ; the data port read"]))
    cases.append(("bydata2", ["ld a,$41", "out (VDP_CTRL),a       ; a second byte, or a first?"]))
    cases.append(("wrap_w", ["in a,(VDP_CTRL)"] + vram_write(0x3FFF) +
                  ["ld a,$C1", "out (VDP_DATA),a", "ld a,$C2", "out (VDP_DATA),a"] + settle()))
    cases.append(("wrap_r", vram_read(0x3FFF) + settle() +
                  ["in a,(VDP_DATA)", f"ld (${RES:04X}),a", "in a,(VDP_DATA)", f"ld (${RES + 1:04X}),a"] +
                  settle()))
    fill = vram_write(PREFETCH)
    for v in (0x11, 0x22, 0x33, 0x44):
        fill += [f"ld a,${v:02X}", "out (VDP_DATA),a"]
    fill += vram_write(AFTER_W)
    for v in (0x55, 0x66, 0x77):
        fill += [f"ld a,${v:02X}", "out (VDP_DATA),a"]
    cases.append(("fill", fill + settle()))
    cases.append(("pre1", vram_read(PREFETCH) + settle()))
    cases.append(("pre2", ["in a,(VDP_DATA)", f"ld (${RES + 2:04X}),a"] + settle()))
    cases.append(("pre3", ["ld a,$EE", "out (VDP_DATA),a       ; a write after reading"] + settle()))
    cases.append(("pre4", ["in a,(VDP_DATA)", f"ld (${RES + 3:04X}),a"] + settle()))
    cases.append(("wthenr", vram_write(AFTER_W) + settle() +
                  ["in a,(VDP_DATA)        ; a read after a write address",
                   f"ld (${RES + 4:04X}),a"] + settle()))
    k4 = ["call clear"] + vdp_reg(1, 0x00, ": the 4 KB mode")
    for k, a in enumerate(MARKS):
        k4 += vram_write(a) + [f"ld a,{k + 1}", "out (VDP_DATA),a"] + settle()
    k4 += vdp_reg(1, BASE_REGS[1], ": 16 KB again")
    cases.append(("k4", k4))
    sp = ["call clear"] + vram_write(0x3800) + ["ld b,8", "pat: ld a,$FF", "out (VDP_DATA),a",
                                                "djnz pat               ; pattern 0: solid"]
    sp += vram_write(0x1B00)
    for y, x in SPRITES:
        sp += [f"ld a,{y}", "out (VDP_DATA),a", f"ld a,{x}", "out (VDP_DATA),a",
               "xor a", "out (VDP_DATA),a", f"ld a,{WHITE}", "out (VDP_DATA),a"]
    sp += ["ld a,$D0", "out (VDP_DATA),a       ; the end of the table"]
    cases.append(("fwait", ["in a,(VDP_CTRL)        ; F cleared", "fpoll: in a,(VDP_CTRL)",
                            "rlca", "jr nc,fpoll            ; until F", "rrca",
                            f"ld (${RES + 5:04X}),a", "in a,(VDP_CTRL)        ; and at once again",
                            f"ld (${RES + 6:04X}),a"]))
    cases.append(("sprites", sp + vdp_reg(1, IE_REGS[1], ": the screen on, no IE") +
                  ["in a,(VDP_CTRL)"] + wait_frames() +
                  ["in a,(VDP_CTRL)        ; after a few frames", f"ld (${RES + 6:04X}),a",
                   "in a,(VDP_CTRL)        ; and at once again", f"ld (${RES + 7:04X}),a"]))
    cases.append(("sprites2", ["fpoll2: in a,(VDP_CTRL)", "rlca",
                               "jr nc,fpoll2           ; until F, which the IN clears"] +
                  wait_frames() +
                  ["in a,(VDP_CTRL)        ; after a few frames", f"ld (${RES + 6:04X}),a",
                   "in a,(VDP_CTRL)        ; and at once again", f"ld (${RES + 7:04X}),a"]))
    for name, r1 in (("ieon", IE_REGS[0]), ("ieoff", IE_REGS[1])):
        cases.append((name + "start", vdp_reg(1, r1) + ["in a,(VDP_CTRL)", "im 1", "ei"]))
        cases.append((name + "end", wait_frames() + ["di"]))
    return cases


WHITE = 15


def vdp():
    say = f"""
; The VDP's registers and ports, case by case: measC.py reads the VDP, and
; the bytes IN gave, kept at ${RES:04X}, at each label v<case>.

init:   di
        ld sp,${STACK:04X}
"""
    body = []
    for name, lines in vdp_cases():
        body.append(f"; {name}")
        body.append(code(local_labels(name, lines)))
        body.append(code(probe_label(name)))
    body.append(code(["jr done"], label="done"))
    return head("vdp", "the VDP's registers and ports") + say + "\n".join(body) + "\n" + CLEAR_VRAM + tail()



# ------------------------------------------------------------------ psg.asm
PSG_BASE = {7: 0xB8, 15: 0x8F}  # the BIOS's: tones and noise off, port A in and B
                                # out; register 15's pins 6 and 7 at 1, 8 at 0,
                                # port A chosen, the lamp off
SELECTS = [0x10, 0x15, 0x25, 0x85, 0xF5]    # register numbers above 15
JOY_FRAMES = 110                # frames of register 14 read from both ports
LAMP_FRAMES = 10                # frames with register 15's bit 7 at 0, then at 1
PINS15 = [0x8F, 0x8E, 0x8D, 0x8B, 0x87, 0x9F, 0xAF]    # register 15 as the BIOS
                                # leaves it, then each of bits 0 to 3 at 0 (pins 6
                                # and 7 of ports A and B), each of 4 and 5 at 1
                                # (pin 8 of A and of B); bit 6 then chooses the port
PORT_B = 0x40                   # register 15, bit 6: port B


def psg_restore(r):
    return psg(r, PSG_BASE.get(r, 0x00), " again")


def psg_cases():
    cases = []
    base = []
    for r in range(16):
        if r != 14:
            base += psg(r, PSG_BASE.get(r, 0x00))
    cases.append(("base", base))
    for r in range(16):
        cases.append((f"keep{r}ff", psg(r, 0xFF) + ["in a,(PSG_READ)", f"ld (${RES + 2 * r:04X}),a"]))
        cases.append((f"keep{r}00", psg(r, 0x00) + ["in a,(PSG_READ)", f"ld (${RES + 2 * r + 1:04X}),a"] +
                      psg_restore(r)))
    at = RES + 32
    for k, v in enumerate(SELECTS):
        cases.append((f"sel{v:02x}", psg(v & 15, 0) + [f"ld a,${v:02X}",
                                                       "out (PSG_ADDR),a       ; above 15",
                                                       "ld a,$5A", "out (PSG_WRITE),a",
                                                       "in a,(PSG_READ)", f"ld (${at + k:04X}),a"]))
        cases.append((f"sel{v:02x}back", psg_restore(v & 15)))
    at += len(SELECTS)
    dirs = [("dirAout", psg(7, 0xF8, ": port A an output") + psg(14, 0x55) +
             ["in a,(PSG_READ)", f"ld (${at:04X}),a"]),
            ("dirAin", psg(7, PSG_BASE[7]) + ["ld a,14", "out (PSG_ADDR),a",
                                              "in a,(PSG_READ)", f"ld (${at + 1:04X}),a"]),
            ("dirBin", psg(7, 0x38, ": port B an input") + psg(15, 0xCA) +
             ["in a,(PSG_READ)", f"ld (${at + 2:04X}),a",
              "ld a,14", "out (PSG_ADDR),a", "in a,(PSG_READ)", f"ld (${at + 3:04X}),a"]),
            ("dirBout", psg(7, PSG_BASE[7]) + psg(15, 0xCA) +
             ["in a,(PSG_READ)", f"ld (${at + 4:04X}),a",
              "ld a,14", "out (PSG_ADDR),a", "in a,(PSG_READ)", f"ld (${at + 5:04X}),a"] +
             psg_restore(15))]
    cases += dirs
    at += 6
    for name, v in (("lamp0", PSG_BASE[15] & 0x7F), ("lamp1", PSG_BASE[15])):
        cases.append((name, psg(15, v) + [f"ld e,{LAMP_FRAMES}", "in a,(VDP_CTRL)",
                                          "lp@: in a,(VDP_CTRL)", "rlca", "jr nc,lp@",
                                          "dec e", f"jr nz,lp@              ; {LAMP_FRAMES} frames"]))
    cases.append(("joystart", [f"ld e,{JOY_FRAMES}", "in a,(VDP_CTRL)"]))
    joy = ["jw: in a,(VDP_CTRL)", "rlca", "jr nc,jw                ; the frame"]
    for k, v in enumerate(PINS15):
        for port in (0, PORT_B):
            joy += psg(15, v | port) + ["ld a,14", "out (PSG_ADDR),a", "in a,(PSG_READ)",
                                        f"ld (${at + 2 * k + (1 if port else 0):04X}),a"]
    cases.append(("joy", joy))
    cases.append(("joyend", ["dec e", "jp nz,jw"] + psg_restore(15)))
    return cases


RES_PSG_JOY = RES + 32 + len(SELECTS) + 6


def psg_():
    say = f"""
; The PSG's registers, case by case: measC.py reads the PSG, the bytes IN
; gave, kept from ${RES:04X}, and the kana lamp at each label p<case>.

init:   di
        ld sp,${STACK:04X}
"""
    body = []
    for name, lines in psg_cases():
        body.append(f"; {name}")
        if name == "joyend":
            body.append(code(local_labels(name, lines)))
            body.append(code([f"p{name}: nop                ; measC.py reads the PSG"]))
            continue
        body.append(code(local_labels(name, lines)))
        body.append(code([f"p{name}: nop                ; measC.py reads the PSG"]))
    body.append(code(["jr done"], label="done"))
    return head("psg", "the PSG's registers") + say + "\n".join(body) + "\n" + tail()



# ------------------------------------------------------------------ ppi.asm
PAGE_ADDR = [0x0000, 0x4000, 0x8000, 0xE000]    # where each page is read, 2 bytes
RAM_MARK = (0x52, 0x4D)         # "RM", at $E000 in the RAM, slot 3
C_BASE = 0x50                   # port C as the BIOS leaves it: row 0, the motor
                                # off, the lamp off, no click
ROW_KEYS = [(r, r % 8) for r in range(11)]      # one key a row, held together
ROW_FROM = 3                    # the frames the rows are read: keys held from 4
ROW_FRAMES = 6
PHASE_FRAMES = 10               # port C's lamp, motor, output and click: two phases
PHASES = [(0x00, "lamp, motor on; 5, 7 turn"),
          (0xD0, "lamp, motor off; click 1")]
TOGGLE_TURNS = 40               # a half period of the toggling: 40 turns of the wait
                                # (measC.py counts its T-states)
CTRL_STARTS = (0x00, 0xFF)      # port C before each of the control port's commands: each
                                # command meets its bit at 0 and at 1
ROUTINE = 0xE100                # the slot routine, copied into the RAM


def ppi_cases():
    cases = []
    at = RES
    sl = ["ld hl,slotrt", f"ld de,${ROUTINE:04X}", "ld bc,slotrt_end-slotrt",
          "ldir                   ; the routine for pages 0 to 2, into the RAM",
          f"ld hl,${RAM_MARK[1] << 8 | RAM_MARK[0]:04X}", f"ld (${PAGE_ADDR[3]:04X}),hl",
          "in a,(PPI_A)", "ld (slots),a"]
    for page in range(4):
        for slot in range(4):
            mask = 3 << 2 * page
            sl += ["ld a,(slots)", f"and ${0xFF ^ mask:02X}", f"or ${slot << 2 * page:02X}",
                   f"ld b,a                 ; page {page} in slot {slot}"]
            if page < 3:
                sl += [f"ld de,${PAGE_ADDR[page]:04X}", f"call ${ROUTINE:04X}"]
            else:
                sl += ["ld a,(slots)", "ld c,a", "ld a,b", "out (PPI_A),a",
                       f"ld hl,(${PAGE_ADDR[3]:04X})", "ld a,c", "out (PPI_A),a          ; back"]
            sl += [f"ld (${at:04X}),hl"]
            at += 2
    cases.append(("slots", sl))
    cases.append(("cback", ["ld hl,$C100", "ld b,0", "ld c,0", "cb: ld a,c", "out (PPI_C),a",
                            "in a,(PPI_C)", "ld (hl),a", "inc hl", "inc c", "djnz cb",
                            f"ld a,${C_BASE:02X}", "out (PPI_C),a"]))
    rows = ["in a,(VDP_CTRL)", f"ld e,{ROW_FROM}", "rw@: in a,(VDP_CTRL)", "rlca", "jr nc,rw@",
            "dec e", "jr nz,rw@              ; to the frame the keys are held",
            f"ld e,{ROW_FRAMES}"]
    cases.append(("rowwait", rows))
    rd = ["rf: in a,(VDP_CTRL)", "rlca", "jr nc,rf", "ld hl,$C200", "ld c,0", "rr: ld a,c",
          f"or ${C_BASE:02X}", "out (PPI_C),a", "in a,(PPI_B)", "ld (hl),a", "inc hl", "inc c",
          "ld a,c", "cp 16", "jr nz,rr                ; rows 0 to 15"]
    cases.append(("rows", rd))
    cases.append(("rowsend", ["dec e", "jr nz,rf", f"ld a,${C_BASE:02X}", "out (PPI_C),a"]))
    ctrl = []
    for start in CTRL_STARTS:
        for b in range(8):
            for v in (0, 1):
                ctrl += [f"ld a,${start:02X}", f"out (PPI_C),a          ; port C = ${start:02X}",
                         f"ld a,${b << 1 | v:02X}", f"out (PPI_MODE),a       ; bit {b} of C to {v}",
                         "in a,(PPI_C)", f"ld (${at:04X}),a"]
                at += 1
    ctrl += ["in a,(PPI_MODE)", f"ld (${at:04X}),a        ; the control port read",
             f"ld a,${C_BASE:02X}", "out (PPI_C),a"]
    at += 1
    cases.append(("ctrl", ctrl))
    for k, (c, what) in enumerate(PHASES):
        ph = [f"ld a,${c:02X}", f"out (PPI_C),a          ; {what}", f"ld d,{PHASE_FRAMES}",
              "in a,(VDP_CTRL)", "ph@: nop"]
        if k == 0:
            ph += [f"ld e,{TOGGLE_TURNS}", "tg@: dec e", "jr nz,tg@", "ld a,c", "xor $A0",
                   "ld c,a", "out (PPI_C),a          ; bits 5 and 7 turned over"]
        ph += ["in a,(VDP_CTRL)", "rlca", "jr nc,ph@", "dec d", "jr nz,ph@"]
        if k == 0:
            ph = [f"ld c,${c:02X}"] + ph
        cases.append((f"phase{k}", ph))
    cases.append(("cend", [f"ld a,${C_BASE:02X}", "out (PPI_C),a"]))
    return cases


RES_PPI_CTRL = RES + 32


def ppi():
    say = f"""
; The PPI, case by case: measC.py reads the PPI and the bytes the program
; kept, from ${RES:04X}, at each label i<case>.
slots   EQU ${RES - 1 + 0x80:04X}       ; port A as the BIOS left it

init:   di
        ld sp,${STACK:04X}
"""
    body = []
    for name, lines in ppi_cases():
        body.append(f"; {name}")
        body.append(code(local_labels(name, lines)))
        body.append(code([f"i{name}: nop                ; measC.py reads the PPI"]))
    body.append(code(["jr done"], label="done"))
    routine = f"""
; slotrt: B into port A, the word at DE into HL, port A back; copied to
; ${ROUTINE:04X}, in the RAM, which the slots it sets do not move
slotrt: ld a,(slots)
        ld c,a
        ld a,b
        out (PPI_A),a
        ex de,hl
        ld e,(hl)
        inc hl
        ld d,(hl)
        ld a,c
        out (PPI_A),a           ; back
        ex de,hl
        ret
slotrt_end:
"""
    return head("ppi", "the PPI's ports, and the slots") + say + "\n".join(body) + "\n" + routine + tail()



# ------------------------------------------------------------------ sound.asm
TONES = [1 << b for b in range(4, 12)] + [0xFFF]   # a tone's period: bits 4 to 11 alone,
                                # then all twelve (bits 0 to 2 alone sound above what a
                                # recording at 44,100 Hz can hold, and bit 3 gets three
                                # samples a period)
VOLUMES = [1, 2, 4, 8, 15]      # a volume: bits 0 to 3 alone, then all four
VOLUME_PERIOD = 0x100           # the tone of the volume phases
SOUND_FRAMES = 25               # frames a phase


def sound_cases():
    """[(name, lines)]: each phase's settings; then the label s<name>, where
    measC.py notes the time, and SOUND_FRAMES frames of the sound"""
    cases = []
    for p in TONES:
        cases.append((f"t{p:03X}", psg(0, p & 0xFF) + psg(1, p >> 8, f": a period of ${p:03X}")))
    cases.append(("tv", psg(0, VOLUME_PERIOD & 0xFF) + psg(1, VOLUME_PERIOD >> 8)))
    for v in VOLUMES:
        cases.append((f"v{v}", psg(8, v, ": the volume")))
    cases.append(("off", psg(8, 0, ": silence")))
    return cases


def sound():
    say = f"""
; Channel A's tone at each period of TONES, then at ${VOLUME_PERIOD:03X} with each
; volume of VOLUMES: {SOUND_FRAMES} frames each. measC.py records the sound, and
; notes the time at each label s<case>.

init:   di
        ld sp,${STACK:04X}
""" + code(psg(7, 0xBE, ": tone A alone") + psg(8, 15, ": the loudest") +
           psg(9, 0) + psg(10, 0)) + "\n"
    body = []
    for name, lines in sound_cases():
        body.append(f"; {name}")
        body.append(code(local_labels(name, lines + [f"s{name}: nop                ; measC.py notes the time",
                                                     f"ld e,{SOUND_FRAMES}", "in a,(VDP_CTRL)",
                                                     "fr@: in a,(VDP_CTRL)", "rlca", "jr nc,fr@",
                                                     "dec e", "jr nz,fr@"])))
    body.append(code(["jr done"], label="done"))
    return head("sound", "a tone's period and its volume, bit by bit") + say + "\n".join(body) + \
        "\n" + tail()


# ------------------------------------------------------------------ keys.asm
KEY_FROM, KEY_EVERY = 150, 8    # the first press (C-BIOS reads no key before), one every 8
TOGGLES = [(6, 3), (6, 4)]      # CAPS, and CODE (KANA on the Japanese machine): pressed,
                                # then A, then pressed again, to put them back
COMBOS = [((6, 0), (2, 6)), ((6, 1), (2, 6)), ((6, 2), (2, 6)), ((6, 4), (2, 6))]
                                # SHIFT, CTRL, GRAPH and CODE, each with A
SHIFT = (6, 0)
SHIFTED = range(6)              # then every key of rows 0 to 5 with SHIFT


def presses():
    """[(frame, [(row, bit), ...])]: every key of rows 0 to 10 alone, each
    toggle with A after it and again, the combinations, and the keys of
    rows 0 to 5 with SHIFT"""
    out, f = [], KEY_FROM
    for r in range(11):
        for b in range(8):
            for k in ([(r, b), (2, 6), (r, b)] if (r, b) in TOGGLES else [(r, b)]):
                out.append((f, [k]))
                f += KEY_EVERY
    for combo in COMBOS:
        out.append((f, list(combo)))
        f += KEY_EVERY
    for r in SHIFTED:
        for b in range(8):
            out.append((f, [SHIFT, (r, b)]))
            f += KEY_EVERY
    return out


def keys():
    say = """
; The BIOS's interrupt reads the keyboard; measC.py presses every key of rows
; 0 to 10, one at a time, and reads each character CHGET gives, at got.

init:   di
        im 1
        VDP_REG 1, $E0          ; the frame's interrupt on
main:   ei
        halt
        call CHSNS              ; a character waiting?
        jr z,main
        call CHGET
got:    nop                     ; measC.py reads A here
        jr main
"""
    return (head("keys", "every key, through the BIOS") + '        INCLUDE "bios.inc"\n' + say +
            tail())



PROGRAMS = {"ports": ports, "vdp": vdp, "psg": psg_, "ppi": ppi, "sound": sound,
            "keys": keys}


def main():
    for f in ("msx.inc", "bios.inc"):
        shutil.copy(os.path.join(REPO, f), os.path.join(HERE, f))
    for name, make in PROGRAMS.items():
        text = tidy(make())
        for line in text.split("\n"):
            assert len(line) <= 78, (name, line)
        with open(os.path.join(HERE, f"{name}.asm"), "w") as f:
            f.write(text)
    print("appendix C:", len(PROGRAMS), "programs")


if __name__ == "__main__":
    main()
