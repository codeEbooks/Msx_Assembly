#!/usr/bin/env python3
"""genC.py - the programs of Appendix C: every port of the book's machine,
and every register of the VDP, the PSG and the PPI, written and read back.

    python3 genC.py && ./build.sh

    ports.asm   all 256 ports read three times, in two states of the
                machine and with B, the high byte of the address, $00 and
                $FF; then all 256 written, in nine passes, each set up so
                that one kind of device shows whether the port reached it:
                the VDP's data port, its control port, the PSG's register
                select, its data, the PPI's ports A and C and its control
                port, the printer's data and its strobe. Every value a pass
                writes keeps page 1 in slot 1, where the program runs, and
                bit 7 at 0, which on the PPI's control port sets or resets a
                bit of port C and does not change the PPI's mode; after each
                OUT the slots are put back before anything reads the RAM.
    vdp.asm     the VDP's registers and ports: what each register keeps,
                register numbers 8 to 15 and bit 6 of the second byte, the
                first byte of an address alone, the latch cleared, the
                address running over $3FFF, reading after a read address
                and after a write address, the 4 KB mode, the status
                register's F, 5S and C, and the interrupt with IE on and off
    psg.asm     the PSG's registers: what each keeps, register numbers above
                15, register 14 with the joysticks, register 15 and its
                port select, and register 7's bits 6 and 7
    ppi.asm     the PPI: the slots, page by page; port C written and read
                back, its rows read through port B, its CAPS lamp, motor,
                cassette output and click; and the control port's sixteen
                commands (measC.py writes two mode words at the end)
    sound.asm   channel A's tone with each bit of its period alone, and its
                volume with each bit alone
    keys.asm    the BIOS's interrupt on, and every character CHGET gives

Every program runs with the interrupts off, but where it says otherwise, and
measC.py reads the machine with the debugger at each label named in it.
build.sh assembles with --syntax=bFw (chapter 15).
"""
