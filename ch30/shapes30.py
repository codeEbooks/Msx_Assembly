def parse(table, width):
    """{code: 7 strings}, codes 32 to 127, each row WIDTH wide"""
    out = {}
    for line in table.strip().splitlines():
        key, rest = line[:5].strip(), line[5:].split()
        code = int(key) if key.isdigit() and len(key) > 1 else ord(key)
        assert len(rest) == 7 and all(len(r) == width and set(r) <= set(".#") for r in rest), line
        out[code] = rest
    assert sorted(out) == list(range(32, 128)), sorted(set(range(32, 128)) - set(out))
    return out


def wide():
    """768 bytes: code 32's eight lines first. The shape in pixels 1 to 5
    of each byte: bit 6 is its left column"""
    out = bytearray()
    for code, rows in sorted(parse(WIDE, 5).items()):
        out.append(0)
        for r in rows:
            out.append(sum(0x40 >> j for j, ch in enumerate(r) if ch == "#"))
    assert len(out) == 768
    return bytes(out)


if __name__ == "__main__":
    print(len(wide()))
