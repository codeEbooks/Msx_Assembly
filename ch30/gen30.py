#!/usr/bin/env python3
"""gen30.py - the programs of chapter 30: fonts and text.

    python3 gen30.py && ./build.sh

    font.inc     the character set of shapes30.py, codes 32 to 127, a byte to
                 a line with the line's picture in the comment
    bios.asm     the BIOS's 256 shapes, from the address at $0004, copied into
                 the patterns, and shown 16 to a row (figure 30.1)
    own.asm      the set of font.inc in patterns 32 to 127, and its 96
                 characters shown (figure 30.2)
    page.asm     a page printed from the ports with at and print, a title in
                 a second copy of the set at codes 160 to 255 in other
                 colours, and a score kept in BCD and shown on the status
                 line every frame (figure 30.3)
    binary.asm   a score kept as a binary number, and printed: five decimal
                 digits counted by subtracting powers of ten, for five numbers
    bar.asm      WHERE IT BREAKS: a status line drawn with the BIOS's set, an
                 energy bar of code 219 (figure 30.4)

Graphic II with one set of shapes and colours for the three thirds (R#3 =
$9F, R#4 = $00, chapter 24). Every program draws with the display off,
keeps the interrupts off, ends with asmparts.CART_END, and build.sh assembles
with --syntax=bFw.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "tools"))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "ch26"))
from asmparts import HEAD, CART_END  # noqa: E402
from gen26 import tidy, db_rows  # noqa: E402  (chapter 26)
import screentext  # noqa: E402  (the BIOS's shapes, from its ROM file)
sys.path.insert(0, HERE)
import shapes30  # noqa: E402

BIOS = '        INCLUDE "bios.inc"\n'
BLACK, WHITE = 1, 15
INK = BLACK << 4 | WHITE        # black ink on white paper
HIGH = WHITE << 4 | BLACK       # the second set: white on black
FIRST = 32                      # the set's first code
SECOND = 128                    # the second copy: codes 160 to 255
EU, JP = "MSXBOOK_EU16", "MSXBOOK_JP16"
REGS = [2, 0xC0, 6, 0x9F, 0, 0x36, 7, 0x0F]


def head(name, what):
    return HEAD.format(name=name, chapter=30, what=what) + BIOS


# ------------------------------------------------------------------ the set
FONT = shapes30.wide()          # 768 bytes: code 32's eight lines first


def font_inc():
    out = ["; font.inc -- chapter 30: the character set of shapes30.py, codes 32 to",
           "; 127, eight bytes each, the top line first; generated by gen30.py",
           "font:"]
    for k in range(96):
        c = FIRST + k
        out.append(f"; {c} {'space' if c == 32 else 'block' if c == 127 else chr(c)}")
        for b in FONT[8 * k:8 * k + 8]:
            pic = "".join("#" if b & 0x80 >> i else "." for i in range(8))
            out.append(f"        db ${b:02X}                  ; {pic}")
    return "\n".join(out) + "\n"


# ------------------------------------------------------------------ the screens
GRID = (4, 8)                   # bios.asm: the 16 x 16 characters from row 4, column 8
OWN_ROW = 1                     # own.asm: the 96 characters in rows 1 to 3
BAR_ROW, LABEL, BAR_AT, BAR_LEN, BAR_CODE = 23, "ENERGY", 9, 12, 219
SCORE_ROW, SCORE_COL = 23, 8    # page.asm: the six digits
SCORE0, POINTS, FRAMES = 1250, 75, 48
NUMBERS = [0, 1250, 4775, 59999, 65535]   # binary.asm: printed in rows 2, 4, 6 ...
NUM_COL = 4

LINES = [   # page.asm: row, column, set, text
    (1, 9, SECOND, " HOW TO PLAY "),
    (4, 3, 0, "Guide the bug through the"),
    (5, 3, 0, "garden and eat every leaf"),
    (6, 3, 0, "before the sun goes down."),
    (8, 3, 0, "Keep away from the birds:"),
    (9, 3, 0, "one touch, and the bug is"),
    (10, 3, 0, "gone."),
    (12, 5, 0, "Cursor keys    move"),
    (13, 5, 0, "Space          jump"),
    (14, 5, 0, "Escape         pause"),
    (16, 3, 0, "A leaf is worth 75 points."),
    (SCORE_ROW, 2, 0, "SCORE"),
]


def score_of(k):
    """the score page.asm shows after k frames' steps"""
    return SCORE0 + POINTS * k


def names_of(kind, k=0):
    """the 768 names a program leaves; for page.asm, with the score after k steps"""
    names = [32] * 768
    if kind == "bios":
        r0, c0 = GRID
        for c in range(256):
            names[32 * (r0 + c // 16) + c0 + c % 16] = c
    elif kind == "own":
        names[32 * OWN_ROW:32 * OWN_ROW + 96] = range(FIRST, FIRST + 96)
    elif kind == "page":
        for row, col, s, text in LINES:
            for i, ch in enumerate(text):
                names[32 * row + col + i] = ord(ch) | s
        for i, d in enumerate(f"{score_of(k):06d}"):
            names[32 * SCORE_ROW + SCORE_COL + i] = ord(d)
    elif kind == "binary":
        for i, n in enumerate(NUMBERS):
            for j, d in enumerate(f"{n:05d}"):
                names[32 * (2 + 2 * i) + NUM_COL + j] = ord(d)
    elif kind == "bar":
        for i, ch in enumerate(LABEL):
            names[32 * BAR_ROW + 2 + i] = ord(ch)
        for i in range(BAR_LEN):
            names[32 * BAR_ROW + BAR_AT + i] = BAR_CODE
    return names


def vram_of(kind, machine=EU, k=0):
    """the shapes, the colours and the names a program leaves, the end of the
    sprites; the BIOS's shapes read from the ROM file of the machine"""
    v = bytearray(16384)
    if kind in ("bios", "bar"):
        shapes, _ = screentext.font(machine)
        v[0:2048] = bytes(b for s in shapes for b in s)
        v[0x2000:0x2800] = bytes([INK]) * 2048
    else:
        v[8 * FIRST:8 * FIRST + 768] = FONT
        v[0x2000:0x2800] = bytes([INK]) * 2048
        if kind == "page":
            v[8 * (SECOND + FIRST):8 * (SECOND + FIRST) + 768] = FONT
            v[0x2400:0x2800] = bytes([HIGH]) * 1024
    v[0x1800:0x1B00] = bytes(names_of(kind, k))
    v[0x1B00] = 0xD0
    return v


# ------------------------------------------------------------------ routines
SETUP = """init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $80          ; display off
        VDP_REG 0, $02          ; Graphic II
        VDP_REG 2, $06          ; names    $1800
        VDP_REG 3, $9F          ; colours  $2000, one set for three thirds
        VDP_REG 4, $00          ; shapes   $0000, one set for three thirds
        VDP_REG 5, $36          ; sprite attributes $1B00
        VDP_REG 6, $07          ; sprite patterns   $3800
        VDP_REG 7, $0F          ; border white
        VRAM_WRITE $1B00        ; no sprites
        ld a, $D0
        out (VDP_DATA), a
"""

SEND = """
; send: E blocks of 256 bytes from HL to the VDP with OTIR, after an address
; is set: the display is off (chapter 20)
send:   ld c, VDP_DATA
        ld b, 0
.otir:  otir
        dec e
        jr nz, .otir
        ret

; fill: E blocks of 256 bytes of A to the VDP, after an address is set
fill:   ld b, 0
.out:   out (VDP_DATA), a
        djnz .out
        dec e
        jr nz, .out
        ret
"""

ON = """        VDP_REG 1, $C0          ; the display on
"""
DONE = "done:   jr done\n"

FRAME = """
; frame: wait for the end of the paper: F, bit 7 of the status, read with the
; interrupts off (chapter 19)
frame:  in a, (VDP_CTRL)
        rla
        jr nc, frame
        ret
"""

PRINT = """
; at: the next characters go to row D, column E: name $1800 + 32 x D + E
at:     ld a, d
        rrca
        rrca
        rrca                    ; the row's bits 0-2 to 5-7, bits 3-4 to 0-1
        ld c, a
        and $E0                 ; 32 x the row, its low byte ...
        or e                    ; ... and the column
        out (VDP_CTRL), a
        ld a, c
        and $03                 ; 32 x the row, its high byte
        or $18 | $40            ; in the name table at $1800, for writing
        out (VDP_CTRL), a
        ret

; print: the characters from HL to the 0 after them, at the address set, in
; the set B says: 0 for the first, $80 for the second
print:  ld a, (hl)              ;  8
        or a                    ;  5
        ret z                   ;  6  the 0: HL is left on it
        or b                    ;  5
        out (VDP_DATA), a       ; 12
        inc hl                  ;  7
        jr print                ; 13: 56 T-states a character

; page: lines of text, each a row, a column, a set and its characters ended
; by 0; $FF after the last
page:   ld a, (hl)
        cp $FF
        ret z
        ld d, a                 ; the row
        inc hl
        ld e, (hl)              ; the column
        inc hl
        ld b, (hl)              ; the set
        inc hl
        call at
        call print
        inc hl                  ; past the 0
        jr page
"""

SCORE = f"""
; show: the score's six digits into the status line, after the paper: a
; digit is a nibble of BCD, and its name is '0' + the nibble
show:   VRAM_WRITE ${0x1800 + 32 * SCORE_ROW + SCORE_COL:04X}        ; row {SCORE_ROW}, column {SCORE_COL}
        ld hl, score
        ld b, 3                 ; three bytes, the highest first
.byte:  ld a, (hl)
        rrca
        rrca
        rrca
        rrca
        and $0F
        add a, '0'
        out (VDP_DATA), a       ; the high nibble's digit
        ld a, (hl)
        and $0F
        add a, '0'
        out (VDP_DATA), a       ; the low nibble's
        inc hl
        djnz .byte
        ret

; step: a leaf eaten, {POINTS} points, added in BCD with DAA (chapter 9)
step:   ld hl, score + 2        ; the lowest two digits
        ld a, (hl)
        add a, ${POINTS:02d}
        daa
        ld (hl), a
        dec hl
        ld a, (hl)
        adc a, 0                ; the carry into the next two
        daa
        ld (hl), a
        dec hl
        ld a, (hl)
        adc a, 0
        daa
        ld (hl), a
        ret
"""


def loop(frames):
    return f"""        ld a, {frames}
        ld (count), a
loop:   call frame              ; the end of the paper
m0:     call show               ; the score, after the paper
m1:     call step               ; the next frame's points
s1:     ld hl, count
        dec (hl)
        jr nz, loop
"""


def names_block(kind):
    return f"names:                          ; 24 rows of 32\n" + db_rows(names_of(kind), 16)


def program(name, what, say, ram, body, routines="", data=""):
    return (head(name, what) + ram + say + tidy(SETUP + body + DONE + routines + SEND) +
            data + CART_END)


# ------------------------------------------------------------------ bios.asm
BIOS_COPY = """c0:     ld hl, (CGTABL)         ; where the BIOS keeps its set
        ld (cgtabl), hl         ; kept, for the debugger
        VRAM_WRITE $0000        ; the shapes: 256 characters of 8 bytes
        ld e, 8
        call send               ; 2,048 bytes
c1:     VRAM_WRITE $2000        ; the colours: black on white
        ld a, ${ink:02X}
        ld e, 8
        call fill
"""


def bios_prog():
    r0, c0 = GRID
    return program("bios", "the BIOS's character set", f"""; The BIOS's 256 shapes, from the address it keeps at $0004 (CGTABL), copied
; into the patterns and shown 16 to a row, from row {r0}, column {c0}.
""", "cgtabl  EQU VARS                ; the address read from CGTABL\n",
        BIOS_COPY.format(ink=INK) + """        VRAM_WRITE $1800        ; the names
        ld hl, names
        ld e, 3
        call send
""" + ON, data=names_block("bios"))


# ------------------------------------------------------------------ own.asm
OWN_COPY = """        VRAM_WRITE $0000        ; the shapes: all paper first
        xor a
        ld e, 8
        call fill
        VRAM_WRITE $2000        ; the colours: black on white
        ld a, ${ink:02X}
        ld e, 8
        call fill
c0:     VRAM_WRITE $0100        ; our set: codes 32 to 127 at pattern 32
        ld hl, font
        ld e, 3
        call send               ; 768 bytes
c1:
"""


def own_prog():
    return program("own", "a set of our own", f"""; The set of font.inc, codes 32 to 127, in patterns 32 to 127, and its 96
; characters in rows {OWN_ROW} to {OWN_ROW + 2}.
""", "", OWN_COPY.format(ink=INK) + """        VRAM_WRITE $1800        ; the names
        ld hl, names
        ld e, 3
        call send
""" + ON, data=names_block("own") + '        INCLUDE "font.inc"\n')


# ------------------------------------------------------------------ page.asm
def lines_block():
    out = "lines:                          ; row, column, set, the text, 0\n"
    for row, col, s, text in LINES:
        out += f'        db {row}, {col}, ${s:02X}, "{text}", 0\n'
    return out + "        db $FF\n"


def page_prog():
    s = f"{SCORE0:06d}"
    return program("page", "printing, a second set, and a score", f"""; A page printed from the ports, a name a character: at sets the address, print
; sends the characters. The title is in a second copy of the set, codes 160 to
; 255, white on black. The status line's score, BCD, is shown every frame.
""", f"""score   EQU VARS                ; the score: three bytes of BCD, the highest first
count   EQU VARS + 3            ; the frames left
""", f"""        VRAM_WRITE $0000        ; the shapes: all paper first
        xor a
        ld e, 8
        call fill
        VRAM_WRITE $2000        ; the colours: codes 0 to 127 black on white ...
        ld a, ${INK:02X}
        ld e, 4
        call fill
        ld a, ${HIGH:02X}                ; ... 128 to 255 white on black
        ld e, 4
        call fill
c0:     VRAM_WRITE $0100        ; our set at 32 ...
        ld hl, font
        ld e, 3
        call send
        VRAM_WRITE $0500        ; ... and again at 160
        ld hl, font
        ld e, 3
        call send
c1:     VRAM_WRITE $1800        ; the names: spaces
        ld a, ' '
        ld e, 3
        call fill
p0:     ld hl, lines
        call page
p1:     ld hl, score            ; the score: {s[:2]} {s[2:4]} {s[4:]}
        ld (hl), ${s[:2]}
        inc hl
        ld (hl), ${s[2:4]}
        inc hl
        ld (hl), ${s[4:]}
        call show
""" + ON + """        in a, (VDP_CTRL)        ; F cleared: the first wait ends with a paper
""" + loop(FRAMES), FRAME + PRINT + SCORE, lines_block() + '        INCLUDE "font.inc"\n')


# ------------------------------------------------------------------ binary.asm
DIGITS = """
; digits: HL, 0 to 65535, as five decimal digits to the address set, the
; highest first: each digit counted by subtracting its power of ten
digits: ld bc, tens
.digit: ld a, (bc)
        ld e, a
        inc bc
        ld a, (bc)
        ld d, a                 ; DE: the next power of ten
        inc bc
        ld a, '0' - 1
.count: inc a                   ;  5
        or a                    ;  5  the carry clear
        sbc hl, de              ; 17
        jr nc, .count           ; 13: 40 T-states a subtraction
        add hl, de              ; one too many: back
        out (VDP_DATA), a       ; the digit
        ld a, e
        dec a                   ; E = 1 only for the last power, 1
        jr nz, .digit
        ret
tens:   dw 10000, 1000, 100, 10, 1
"""


def binary_prog():
    calls = ""
    for i, n in enumerate(NUMBERS):
        calls += f"""        ld d, {2 + 2 * i}                 ; the row
        ld e, {NUM_COL}                 ; the column
        call at
        ld hl, {n}
n{i}:     call digits
n{i}e:
"""
    return program("binary", "a score in binary, printed", f"""; A score kept as a binary number must be divided by ten to be printed. digits
; counts each decimal digit by subtracting its power of ten; five numbers.
""", "", OWN_COPY.format(ink=INK) + """        VRAM_WRITE $1800        ; the names: spaces
        ld a, ' '
        ld e, 3
        call fill
""" + calls + ON, DIGITS + PRINT[:PRINT.index("; print:")].rstrip() + "\n",
        '        INCLUDE "font.inc"\n')


# ------------------------------------------------------------------ bar.asm
def bar_prog():
    return program("bar", "a status line in the BIOS's set", f"""; WHERE IT BREAKS. A status line drawn with the BIOS's set: "{LABEL}" and a bar of
; {BAR_LEN} characters {BAR_CODE}, a block on the 50 Hz machine.
""", "cgtabl  EQU VARS                ; the address read from CGTABL\n",
        BIOS_COPY.format(ink=INK) + """        VRAM_WRITE $1800        ; the names
        ld hl, names
        ld e, 3
        call send
""" + ON, data=names_block("bar"))


PROGRAMS = {"bios": bios_prog, "own": own_prog, "page": page_prog, "binary": binary_prog,
            "bar": bar_prog}


def main():
    with open(os.path.join(HERE, "font.inc"), "w") as f:
        f.write(font_inc())
    for name, make in PROGRAMS.items():
        with open(os.path.join(HERE, f"{name}.asm"), "w") as f:
            f.write(make())
    print("font.inc " + " ".join(f"{n}.asm" for n in PROGRAMS))


if __name__ == "__main__":
    main()
