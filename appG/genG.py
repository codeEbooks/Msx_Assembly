#!/usr/bin/env python3
"""genG.py - the programs of Appendix G, which try sjasmplus and openMSX.

    python3 genG.py && ./build.sh

    probe.asm   every directive the sources of this book use, each with as many
                operands as the book gives it, in an order whose bytes
                measG.py can foretell: INCLUDE, OUTPUT (and OUTPUT ..., a),
                OUTEND, ORG, db (strings in both quotes), dw, dd, ds (with a
                fill and without), DUP (with a counter and without), ALIGN
                (with a fill and without), ASSERT (with a text and without),
                EQU, =, MACRO, STRUCT (BYTE and WORD fields, an instance with
                its defaults and one with {...}), DISP, INCBIN, IFNDEF,
                DISPLAY; numbers written six ways. It writes probe.bin, not a
                cartridge; build.sh also writes probe.lst and probe.sym.
    probe.inc   the file probe.asm includes: one name.
    blob.bin    the three bytes probe.asm takes in with INCBIN.
    cart.asm    a cartridge for the console sessions: it sets the border,
                writes a byte to the VRAM, calls a subroutine and stops.
    tape.wav    a tenth of a second of silence, for -cassetteplayer.
    cases/      a line or a few, for the options measG.py tries: a number
                that does not fit (warn.asm), a fake instruction (fake.asm),
                a register loaded from parentheses (paren.asm), a name the
                command line may define (define.asm, value.asm) and one EQU
                defines (equ.asm), a hexadecimal number written wrong
                (hex.asm), two ASSERTs that fail, with a text and without
                (assert.asm).

build.sh assembles probe.asm and cart.asm with the book's options
(--syntax=bFw, chapter 15).
"""
import os
import struct
import sys
import wave

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(REPO, "tools"))
sys.path.insert(0, os.path.join(REPO, "ch26"))
from asmparts import CART_END  # noqa: E402
from gen26 import tidy  # noqa: E402  (chapter 26)

PROBE_INC = 0x5A                # the name probe.inc defines
BLOB = bytes([0xDE, 0xAD, 0xBE])
ORG = 0x4000
DISP_AT = 0xC000
ALIGN_TO = 16
DUP_N = 2
VRAM_AT, VRAM_BYTE = 0x1800, 0x47       # cart.asm's byte to the VRAM, a G

# lines 3 to 15 of probe.lst are Listing G.1: they hold every mark of the
# listing, so the directives that make them come first
PROBE = f"""; probe.asm -- appendix G: every directive this book's sources use
; generated by genG.py
        INCLUDE "probe.inc"             ; PROBE_INC, a name
        OUTPUT "probe.bin"
        ORG ${ORG:04X}
start:  db 1, "AB", 3>2, 3<2, low $1234, high $1234
        DUP {DUP_N}, k                        ; k counts from 0
        db $A0 + k
        EDUP
        ALIGN {ALIGN_TO}
aligned: db $BB
        MACRO TWICE value
        db value, value
        ENDM
        TWICE $77
        ASSERT aligned % {ALIGN_TO} == 0, not aligned
        dw $1234, start
        dd $12345678
        ds 3, $55
        DUP 2                           ; no counter
        db $AA
        EDUP
        db PROBE_INC
        ds 2                            ; no fill: zeros
        ALIGN 4, $99                    ; a fill of its own
here:   db '#'                          ; a character
        ASSERT $ == here + 1            ; $: this line's address
FIVE    EQU 5
COUNT = 1                       ; a name that may change
COUNT = COUNT + FIVE
        db COUNT
        STRUCT POINT
x       BYTE 1
y       BYTE 2
w       WORD $1234
        ENDS
p1      POINT                           ; the defaults
p2      POINT {{7, 8, $ABCD}}
        db POINT, POINT.w               ; the size, an offset
        DISP ${DISP_AT:04X}
moved:  dw moved                        ; assembled for ${DISP_AT:04X}, stored here
        ENT
after:  dw after
        INCBIN "blob.bin"
        IFNDEF NOWHERE                  ; sjasmplus -DNOWHERE would leave it out
        db $CC
        ENDIF
        db $10, #10, 0x10, 10h, 0FFh, %101
        DISPLAY "aligned at ",/H,aligned
        OUTEND
        db $DD                          ; in no file
        OUTPUT "probe.bin", a           ; on at the end of probe.bin
        db $EE
        OUTEND
"""
CART = f"""; cart.asm -- appendix G: a cartridge for the console sessions
; generated by genG.py
        INCLUDE "msx.inc"
        OUTPUT "cart.rom"
        ORG $4000
        CART_HEADER init
init:   di
        VDP_REG 7, LIGHT_GREEN          ; the border
        VRAM_WRITE ${VRAM_AT:04X}
        ld a, ${VRAM_BYTE:02X}
        out (VDP_DATA), a               ; a G at the top left of the page
        call sub
back:   nop
stop:   jr stop

sub:    ld b, 3
sloop:  djnz sloop
        ret
{CART_END}"""

CASES = {
    "warn": "        ld a, 256               ; does not fit in a byte\n",
    "fake": "        ld hl, de               ; no such instruction: a fake one\n",
    "paren": "        ld b, ($C000)           ; no LD B,(nn) either\n",
    "define": "        IFNDEF FAST\n        db 2\n        ENDIF\n        db 1\n",
    "equ": "FAST    EQU 1\n        IFNDEF FAST\n        db 2\n        ENDIF\n        db 1\n",
    "value": "        db FAST\n",
    "hex": "        db FFh                  ; a name, not a number\n",
    "assert": "FIVE    EQU 5\n        ASSERT FIVE == 6, FIVE is not 6\n        ASSERT FIVE == 7\n",
}


def case(name, body):
    return (f"; {name}.asm -- appendix G: a case for an option of sjasmplus\n"
            f"; generated by genG.py\n        OUTPUT \"{name}.bin\"\n        ORG $4000\n" + body)


def tape():
    """a tenth of a second of silence, 8-bit mono at 44,100 Hz"""
    with wave.open(os.path.join(HERE, "tape.wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(1)
        w.setframerate(44100)
        w.writeframes(struct.pack("B", 128) * 4410)


def main():
    os.makedirs(os.path.join(HERE, "cases"), exist_ok=True)
    with open(os.path.join(HERE, "probe.asm"), "w") as f:
        f.write(tidy(PROBE))
    with open(os.path.join(HERE, "probe.inc"), "w") as f:
        f.write(f"; probe.inc -- appendix G: the file probe.asm includes\n"
                f"PROBE_INC EQU ${PROBE_INC:02X}\n")
    with open(os.path.join(HERE, "blob.bin"), "wb") as f:
        f.write(BLOB)
    with open(os.path.join(HERE, "cart.asm"), "w") as f:
        f.write(tidy(CART))
    for name, body in CASES.items():
        with open(os.path.join(HERE, "cases", f"{name}.asm"), "w") as f:
            f.write(tidy(case(name, body)))
    tape()
    for name in ("msx.inc",):
        with open(os.path.join(REPO, name)) as a, open(os.path.join(HERE, name), "w") as b:
            b.write(a.read())
    print("appendix G: probe.asm, cart.asm,", len(CASES), "cases, tape.wav")


if __name__ == "__main__":
    main()
