#!/usr/bin/env python3
"""gen01.py -- writes the sources of chapter 1.

Every program of the chapter is generated here from a few shared pieces, so
that the same set-up is the same code everywhere. Run it, then build.sh.

  fill_order        Graphic II, the pattern table filled in address order,
                    32 bytes a frame: the order in which bytes become pixels
  clash_none        a field of grass and a ball drawn into the patterns
  clash_ball        the same, with the colour strips under the ball made white
  sprites5          five hardware sprites on the same lines: one disappears
  sprites5_down     the same with the fifth sprite sixteen lines lower
  y208, y209        Where it breaks: a sprite parked at Y = 208 and at Y = 209
  bios_fill         768 bytes into the name table three ways: BIOS WRTVRM per
                    byte, BIOS LDIRVM, and OUTI from a loop of our own
  beam_000/016/228  the border stripe, 0, 16 and 228 T-states later; it stands
                    still from frame to frame (asmparts.steady)
  tick              a sprite that moves one pixel a frame (50 Hz against 60 Hz)
  palette           the sixteen colour codes
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "tools"))
from asmparts import steady  # noqa: E402

# ---------------------------------------------------------------- pieces
HEAD = '''; {name}.asm -- chapter 1: {what}
; generated by gen01.py
        INCLUDE "msx.inc"
        OUTPUT "{name}.rom"
        ORG $4000
        CART_HEADER init
'''
TAIL = '''        ds $8000 - $, $FF       ; pad the cartridge to 16 KB
        ASSERT $ == $8000
'''

NAME, COLOUR, PATTERN, SPRATR, SPRPAT = 0x1800, 0x2000, 0x0000, 0x1B00, 0x3800


def graphic2(border, colour_byte, sprites16=False):
    """Graphic II with the book's tables, display off; clear the VRAM, names
    0-255 in each third, the whole colour table set to colour_byte, sprites
    switched off by a Y of 208 in plane 0."""
    return f'''init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $80          ; 16 KB, display off
        VDP_REG 0, $02          ; Graphic II
        VDP_REG 2, $06          ; names              $1800
        VDP_REG 3, $FF          ; colours            $2000
        VDP_REG 4, $03          ; patterns           $0000
        VDP_REG 5, $36          ; sprite attributes  $1B00
        VDP_REG 6, $07          ; sprite patterns    $3800
        VDP_REG 7, {border}          ; border colour
        VRAM_WRITE 0            ; clear all 16 KB
        ld bc, $4000
.clear: xor a
        out (VDP_DATA), a
        dec bc
        ld a, b
        or c
        jr nz, .clear
        VRAM_WRITE $1800        ; names: 0-255 in each third
        ld c, 3
.third: xor a
.name:  out (VDP_DATA), a
        inc a
        jr nz, .name
        dec c
        jr nz, .third
        VRAM_WRITE $2000        ; colours: {colour_byte:#04x} everywhere
        ld bc, 6144
.col:   ld a, ${colour_byte:02X}
        out (VDP_DATA), a
        dec bc
        ld a, b
        or c
        jr nz, .col
        VRAM_WRITE $1B00        ; no sprites yet
        ld a, $D0
        out (VDP_DATA), a
'''


DISPLAY_ON = '''        VDP_REG 1, ${r1:02X}          ; display on{extra}
'''


def display_on(sprites16=False):
    return DISPLAY_ON.format(r1=0xC2 if sprites16 else 0xC0,
                             extra=", 16 x 16 sprites" if sprites16 else "")


WAIT_FRAME = '''.wait:  in a, (VDP_CTRL)        ; wait for the frame flag (status bit 7)
        rlca
        jr nc, .wait
'''


def ball_pattern():
    """A 16 x 16 ball, as the 32 bytes of a sprite pattern (four 8 x 8 quarters:
    top left, bottom left, top right, bottom right)."""
    rows = []
    for y in range(16):
        r = 0
        for x in range(16):
            if (x - 7.5) ** 2 + (y - 7.5) ** 2 <= 7.6 ** 2:
                r |= 0x8000 >> x
        rows.append(r)
    left = [r >> 8 for r in rows]
    right = [r & 0xFF for r in rows]
    return left[:8] + left[8:] + right[:8] + right[8:], rows


def db(values, per=8):
    out = []
    for i in range(0, len(values), per):
        out.append("        db " + ", ".join(f"${v:02X}" for v in values[i:i + per]))
    return "\n".join(out)


def sprite_setup(sprites):
    """The ball as sprite pattern 0, and the attribute table from `sprites`:
    a list of (y, x, colour); a Y of 208 is written as given."""
    pat, _ = ball_pattern()
    attrs = []
    for y, x, c in sprites:
        attrs += [y, x, 0, c]
    attrs.append(0xD0)
    return f'''        VRAM_WRITE $3800        ; sprite pattern 0: the ball
        ld hl, ball
        ld b, 32
.pat:   ld a, (hl)
        out (VDP_DATA), a
        inc hl
        djnz .pat
        VRAM_WRITE $1B00        ; the attribute table: Y, X, pattern, colour
        ld hl, attrs
        ld b, {len(attrs)}
.att:   ld a, (hl)
        out (VDP_DATA), a
        inc hl
        djnz .att
''', f'''ball:
{db(pat)}
attrs:                          ; Y, X, pattern, colour ... and $D0
{db(attrs, 4)}
'''


def write(name, text):
    (HERE / f"{name}.asm").write_text(text)


# ---------------------------------------------------------------- programs
def fill_order():
    write("fill_order", HEAD.format(name="fill_order",
                                    what="the screen filled in the order of its addresses") +
          graphic2(4, 0xF1) + display_on() + '''
        VRAM_WRITE $0000        ; the first byte of the pattern table
        ld e, 192               ; 192 frames x 32 bytes = 6,144 bytes
frame:  in a, (VDP_CTRL)        ; wait for the frame flag (status bit 7)
        rlca
        jr nc, frame
        ld b, 32                ; 32 bytes of $FF, one after the other
        ld a, $FF
byte:   out (VDP_DATA), a       ; the VDP moves on to the next address
        djnz byte
        dec e
        jr nz, frame
done:   jr done
''' + TAIL)


def grass_byte(y):
    return [0x88, 0x22, 0x44, 0x11][y % 4]


BALL_X, BALL_Y = 124, 92


def ball_cells():
    """The cells the ball touches, with their 8 pattern bytes: grass, and the
    ball's pixels on top."""
    _, rows = ball_pattern()
    out = {}
    for cy in range(BALL_Y // 8, (BALL_Y + 15) // 8 + 1):
        for cx in range(BALL_X // 8, (BALL_X + 15) // 8 + 1):
            b8 = []
            for line in range(8):
                y = cy * 8 + line
                v = grass_byte(y)
                if BALL_Y <= y < BALL_Y + 16:
                    r = rows[y - BALL_Y]
                    for bit in range(8):
                        x = cx * 8 + bit
                        if BALL_X <= x < BALL_X + 16 and r & (0x8000 >> (x - BALL_X)):
                            v |= 0x80 >> bit
                b8.append(v)
            out[(cy, cx)] = b8
    return out


def pattern_addr(cy, cx):
    third, row = divmod(cy, 8)
    return third * 2048 + row * 256 + cx * 8


def clash(name, white):
    cells = ball_cells()
    lines = []
    for (cy, cx), b8 in sorted(cells.items()):
        lines.append(f"        dw ${pattern_addr(cy, cx):04X}")
        lines.append(db(b8))
    # the colour strips under the ball: rows BALL_Y..BALL_Y+15 of the touched cells
    strips = []
    for (cy, cx) in sorted(cells):
        for line in range(8):
            y = cy * 8 + line
            if BALL_Y <= y < BALL_Y + 16:
                strips.append(COLOUR + pattern_addr(cy, cx) + line)
    white_code = ""
    if white:
        white_code = f'''        ld hl, strips           ; the colour strips under the ball: white ink
        ld b, {len(strips)}
strip:  ld e, (hl)
        inc hl
        ld d, (hl)
        inc hl
        ld a, e
        out (VDP_CTRL), a
        ld a, d
        or $40
        out (VDP_CTRL), a
        ld a, $F1               ; ink 15 (white), paper 1 (black)
        out (VDP_DATA), a
        djnz strip
'''
    write(name, HEAD.format(name=name, what="a ball on a field of grass" +
                            (", with white ink under the ball" if white else "")) +
          graphic2(1, 0x21) + f'''        VRAM_WRITE $0000        ; the grass: two dots in every byte
        ld bc, 6144
        ld d, 0
grass:  ld a, d
        and 3
        ld hl, dots
        add a, l
        ld l, a
        ld a, (hl)
        out (VDP_DATA), a
        inc d
        dec bc
        ld a, b
        or c
        jr nz, grass
        ld hl, cells            ; the ball, drawn into the cells it covers
        ld c, {len(cells)}
cell:   ld e, (hl)
        inc hl
        ld d, (hl)
        inc hl
        ld a, e
        out (VDP_CTRL), a
        ld a, d
        or $40
        out (VDP_CTRL), a
        ld b, 8
pixels: ld a, (hl)
        out (VDP_DATA), a
        inc hl
        djnz pixels
        dec c
        jr nz, cell
''' + white_code + display_on() + '''done:   jr done
        ALIGN 4
dots:   db $88, $22, $44, $11
cells:                          ; address, then the 8 bytes of each cell
''' + "\n".join(lines) + "\n" + ("strips:\n" + "\n".join(f"        dw ${a:04X}" for a in strips) + "\n"
                                  if white else "") + TAIL)


SPRITE_ROW = [(80, 16 + 48 * i, 15) for i in range(5)]


def sprites(name, rows, what):
    code, data = sprite_setup(rows)
    write(name, HEAD.format(name=name, what=what) + graphic2(1, 0x11) + code +
          display_on(True) + '''        xor a
        ld (RAM_START), a
frame:  in a, (VDP_CTRL)        ; read the status, again and again
        bit 6, a                ; the fifth-sprite flag?
        jr z, .no5
        ld (RAM_START), a       ; keep the status that had it
.no5:   rlca                    ; the frame flag?
        jr nc, frame
        jr frame
''' + data + TAIL)


def bios_fill():
    write("bios_fill", HEAD.format(name="bios_fill",
                                   what="768 bytes into the name table, three ways") + '''
WRTVRM  EQU $004D               ; BIOS: write A to VRAM address HL
LDIRVM  EQU $005C               ; BIOS: copy BC bytes from (HL) to VRAM address DE
init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $C0          ; Graphic I, display on
        VDP_REG 0, $00
        VDP_REG 2, $06          ; names at $1800
by_bios_byte:                   ; 1. one BIOS call per byte
        ld hl, $1800
        ld bc, 768
.next:  ld a, 1
        call WRTVRM
        inc hl
        dec bc
        ld a, b
        or c
        jr nz, .next
by_bios_block:                  ; 2. one BIOS call for the block
        ld hl, twos
        ld de, $1800
        ld bc, 768
        call LDIRVM
by_ports:                       ; 3. our own loop on the two ports
        di
        VRAM_WRITE $1800
        ld hl, threes
        ld c, VDP_DATA
        ld d, 3                 ; 3 x 256 bytes
.block: ld b, 0
.byte:  outi                    ; 18 T on the MSX ...
        jp nz, .byte            ; ... + 11: 29 T a byte
        dec d
        jr nz, .block
finished:
        jr finished
twos:   ds 768, 2
threes: ds 768, 3
''' + TAIL)


def beam(k):
    name = f"beam_{k:03d}"
    pre = ["nop"] * 99 + ["ld a,(hl)"]          # 99 x 5 + 8 = 503 T after IN A,(n)
    mid = ["nop"] * 4                            # 20 T between the two writes
    extra = {0: [], 16: ["ld a,(hl)"] * 2, 228: ["ld a,(hl)"] * 1 + ["nop"] * 44}[k]
    assert sum({"nop": 5, "ld a,(hl)": 8}[i] for i in extra) == k
    body = "\n".join(f"        {i}" for i in pre + extra)
    handler = (["        in a, (VDP_CTRL)"] + body.splitlines() +
               ["        out (c), b", "white:  out (c), e"] + [f"        {i}" for i in mid] +
               ["        out (c), d", "black:  out (c), e"])
    still = "".join(line + "\n" for line in steady(handler))
    write(name, HEAD.format(name=name, what=f"a white stripe in the border, {k} T later") + '''
IM2_TABLE EQU $C100             ; 257 bytes of $C2: the interrupt vector is $C2C2
IM2_JUMP  EQU $C2C2
init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $80          ; display off while we set up
        VDP_REG 0, $00          ; Graphic I
        VDP_REG 2, $06
        VDP_REG 3, $80
        VDP_REG 4, $00
        VDP_REG 5, $36
        VDP_REG 6, $07
        VDP_REG 7, $01          ; border black
        VRAM_WRITE $2000        ; colour table: black on black
        ld b, 32
        ld a, $11
.col:   out (VDP_DATA), a
        djnz .col
        VRAM_WRITE $1B00        ; no sprites
        ld a, $D0
        out (VDP_DATA), a
        ld hl, IM2_TABLE        ; the IM 2 table
        ld (hl), $C2
        ld de, IM2_TABLE + 1
        ld bc, 256
        ldir
        ld a, $C3               ; JP handler, at $C2C2
        ld (IM2_JUMP), a
        ld hl, handler
        ld (IM2_JUMP + 1), hl
        ld a, high IM2_TABLE
        ld i, a
        im 2
        ld c, VDP_CTRL          ; kept for the handler
        ld b, $0F               ; white
        ld d, $01               ; black
        ld e, $87               ; register 7
        ld hl, RAM_START
        VDP_REG 1, $E0          ; display on, frame interrupt on
        ei
main:   halt
        jr main
handler:
        in a, (VDP_CTRL)        ; reading the status acknowledges the interrupt
''' + body + '''
        out (c), b              ; value: white
white:  out (c), e              ; R#7 <- white
''' + "\n".join(f"        {i}" for i in mid) + '''
        out (c), d              ; value: black
black:  out (c), e              ; R#7 <- black
''' + still + '''        ei
        ret
''' + TAIL)


def tick():
    code, data = sprite_setup([(88, 0, 15)])
    write("tick", HEAD.format(name="tick", what="a sprite that moves one pixel every frame") +
          graphic2(1, 0x11) + code + display_on(True) + '''        ld e, 0                 ; X
frame:  in a, (VDP_CTRL)        ; wait for the frame flag
        rlca
        jr nc, frame
        inc e                   ; one pixel to the right, every frame
        VRAM_WRITE $1B01        ; X of sprite 0
        ld a, e
        out (VDP_DATA), a
        jr frame
''' + data + TAIL)


def palette():
    write("palette", HEAD.format(name="palette", what="the sixteen colour codes") + '''
NAMES   EQU $1800
COLOURS EQU $2000
init:   di
        ld sp, SYS_AREA
        VDP_REG 1, $80          ; display off while we set up
        VDP_REG 0, $00          ; Graphic I
        VDP_REG 2, NAMES / $400
        VDP_REG 3, COLOURS / $40
        VDP_REG 4, $00
        VDP_REG 5, $36
        VDP_REG 6, $07
        VDP_REG 7, $01          ; border black
        VRAM_WRITE $0000        ; patterns 8*c solid, the others empty
        ld d, 0
.pat:   ld a, d
        and 7
        ld a, 0
        jr nz, .empty
        dec a
.empty: ld b, 8
.row:   out (VDP_DATA), a
        djnz .row
        inc d
        jr nz, .pat
        VRAM_WRITE COLOURS      ; group c: ink c, paper 0
        xor a
.grp:   push af
        add a, a
        add a, a
        add a, a
        add a, a
        out (VDP_DATA), a
        pop af
        inc a
        cp 32
        jr nz, .grp
        VRAM_WRITE $1B00
        ld a, $D0
        out (VDP_DATA), a
        VRAM_WRITE NAMES        ; 4 x 4 swatches of 7 x 6 tiles
        ld e, 0
.nrow:  ld d, 0
.ncol:  ld a, d
        srl a
        srl a
        srl a
        ld b, a
        ld a, e
        ld c, 0
.div6:  cp 6
        jr c, .q
        sub 6
        inc c
        jr .div6
.q:     ld a, c
        add a, a
        add a, a
        add a, b
        add a, a
        add a, a
        add a, a
        ld c, a
        ld a, d
        and 7
        cp 7
        ld a, c
        jr nz, .put
        ld a, 1
.put:   out (VDP_DATA), a
        inc d
        ld a, d
        cp 32
        jr nz, .ncol
        inc e
        ld a, e
        cp 24
        jr nz, .nrow
        VDP_REG 1, $C0
done:   jr done
''' + TAIL)


def main():
    fill_order()
    clash("clash_none", False)
    clash("clash_ball", True)
    sprites("sprites5", SPRITE_ROW, "five sprites on the same lines")
    sprites("sprites5_down", SPRITE_ROW[:4] + [(SPRITE_ROW[4][0] + 32, SPRITE_ROW[4][1], 15)],
            "the same, with the fifth sprite 32 lines lower")
    stack = [(24, 32, 15), (56, 80, 15), (208, 128, 15), (88, 176, 15), (120, 224, 15)]
    sprites("y208", stack, "five sprites; the third is parked at Y = 208")
    stack[2] = (209, 128, 15)
    sprites("y209", stack, "five sprites; the third is parked at Y = 209")
    bios_fill()
    for k in (0, 16, 228):
        beam(k)
    tick()
    palette()
    print("ok")


if __name__ == "__main__":
    main()
