#!/usr/bin/env python3
"""genB.py - the programs of Appendix B: every instruction Zilog's manual
leaves out, timed and run; and every instruction, documented or not, run
again for what no manual shows: bits 3 and 5 of F, and MEMPTR.

    python3 genB.py && ./build.sh

    undoc.asm     each of isetB.py's 1,086 instructions once, between two
                  labels, as Appendix A's times.asm runs the documented
                  ones: t before it, e after it, where every jump goes; the
                  jumps on a condition twice, the RSTs twice. measB.py stops
                  at every label.
    hidden_1.asm  the instructions of Appendix A (but HALT and RST) and of
    hidden_2.asm  isetB.py (but the RSTs), run from a table as Appendix A's
                  flags.asm runs them, with its states, a few more, and the
                  same eight Fs: two cartridges of 32 KB, half the table
                  each. Each instruction is copied first into the RAM, to
                  end just where after begins: nothing runs between it and
                  the debugger's stop, which would change MEMPTR, the
                  address the processor keeps inside. Before it goes base,
                  LD ($1356),SP, which puts $1357 in MEMPTR. At after, and
                  at away, where the jumps go, a BIT 0,(HL) puts bits 5 and
                  3 of MEMPTR's high byte in F, where the debugger reads
                  them: openMSX's debugger has no MEMPTR to show. Some
                  instructions run again, to tell rules apart (extra(),
                  below).

build.sh assembles with --syntax=bFw (chapter 15).
"""
