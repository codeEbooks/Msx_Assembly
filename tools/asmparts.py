AT_PUTC = '''
; at: B = row (0-23), C = column (0-31) -> the VDP's write address is that
;     cell of the name table. Keeps BC, DE. Uses A, HL.
at:     push de
        ld l, b
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl              ; row x 32
        ld e, c
        ld d, $18
        add hl, de              ; + $1800 + column
        ld a, l
        out (VDP_CTRL), a
        ld a, h
        or $40
        out (VDP_CTRL), a
        pop de
        ret

; putc: A = character, B = row, C = column. Keeps BC, DE, HL.
putc:   push hl
        push af
        call at
        pop af
        out (VDP_DATA), a
        pop hl
        ret

; puts: HL = text ending in 0, B = row, C = column; C moves on.
puts:   ld a, (hl)
        or a
        ret z
        call putc
        inc hl
        inc c
        jr puts

; puthex: A = a byte, as two hexadecimal digits; C moves on by 2.
puthex: push af
        rrca
        rrca
        rrca
        rrca                    ; the high four bits first
        call hexdig
        pop af
hexdig: and %00001111
        add a, '0'
        cp '9' + 1
        jr c, .digit
        add a, 'A' - '9' - 1    ; 10-15 become A-F
.digit: call putc
        inc c
        ret
'''

PUTDEC = '''
; putdec: A = a byte taken as unsigned (0-255): three characters, right-aligned
; putsgn: A = a byte taken as signed (-128 to 127): four characters
;         C moves on by 3 or 4. Uses A, DE, HL.
putdec: push bc
        ld d, ' '
        call digits
        pop bc
        ld hl, numbuf + 1
        ld e, 3
        jr pnout
putsgn: push bc
        ld d, ' '
        bit 7, a                ; the top bit is the sign
        jr z, .pos
        neg                     ; two's complement: the size of the number
        ld d, '-'
.pos:   call digits
        pop bc
        ld hl, numbuf
        ld e, 4
pnout:  ld a, (hl)
        call putc
        inc c
        inc hl
        dec e
        jr nz, pnout
        ret

; digits: A (0-255) into numbuf in decimal, right-aligned, D just left of
;         the first digit. Uses A, C, HL.
digits: ld hl, numbuf
        ld (hl), ' '
        inc hl
        ld (hl), ' '
        inc hl
        ld (hl), ' '
        inc hl
        ld (hl), ' '            ; HL: the last character
.next:  ld c, 0                 ; C: A divided by 10
.ten:   cp 10
        jr c, .rest
        sub 10
        inc c
        jr .ten
.rest:  add a, '0'
        ld (hl), a              ; the remainder is this digit
        dec hl
        ld a, c
        or a
        jr nz, .next            ; and the quotient is what is left
        ld (hl), d              ; the sign, or a space
        ret
numbuf  EQU VARS                ; 4 bytes of RAM
'''

FATBITS = f'''
; fatbits: A = a byte, drawn as 8 boxes, bit 7 first: a filled box for 1,
;          an empty one for 0. B = row, C = column; C moves on by 8.
;          Uses A. Keeps HL.
fatbits:
        push hl
        ld l, a
        ld h, 8
.bit:   ld a, {BOX_EMPTY}                 ; an empty box ...
        rl l                    ; the next bit, into the carry
        jr nc, .put
        ld a, {BOX_FULL}                 ; ... or a filled one
.put:   call putc
        inc c
        dec h
        jr nz, .bit
        pop hl
        ret
'''

PUTD16 = """
; putd16: HL = a number (0-65535) as five characters, right-aligned.
;         B = row, C = column; C moves on by 5. Uses A, DE, HL.
putd16: push bc
        ld de, d16buf
        ld bc, -10000
        call .digit
        ld bc, -1000
        call .digit
        ld bc, -100
        call .digit
        ld bc, -10
        call .digit
        ld a, l
        add a, '0'
        ld (de), a              ; the units, always printed
        ld hl, d16buf
        ld b, 4
.blank: ld a, (hl)              ; leading zeros become spaces
        cp '0'
        jr nz, .print
        ld (hl), ' '
        inc hl
        djnz .blank
.print: pop bc
        ld hl, d16buf
        ld e, 5
.out:   ld a, (hl)
        call putc
        inc c
        inc hl
        dec e
        jr nz, .out
        ret
.digit: ld a, '0' - 1           ; how many times BC fits: subtract until it goes below
.sub:   inc a
        add hl, bc              ; BC is negative: the carry means it still fitted
        jr c, .sub
        sbc hl, bc              ; one too many: add it back (the carry is clear)
        ld (de), a
        inc de
        ret
d16buf  EQU VARS + 4            ; 5 bytes of RAM, after numbuf
"""

