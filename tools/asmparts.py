BOXES = "boxes:                          ; characters 1 (empty box) and 2 (filled)\n" + "\n".join(
    "        db " + ", ".join(f"%{b:08b}" for b in BOX_SHAPES[k]) for k in (BOX_EMPTY, BOX_FULL)) + "\n"


def library(*parts, interrupts=False):
    """the routines a program needs, AT_PUTC always first, the boxes always last;
    interrupts=True: the at of AT_ON, for a program that prints with the
    interrupts on (chapter 19)"""
    return (AT_ON if interrupts else AT_PUTC) + "".join(parts) + BOXES


# ---------------------------------------------------------------- at, with the interrupts on
# The two OUTs of at are one address. An interrupt between them, whose routine
# reads the status as every routine must (chapter 17), makes the VDP forget the
# first byte, take the second for the first of a new pair, and put what comes
# next in the wrong place (chapter 19, split.asm). This at sets the address with
# the interrupts off and then leaves them as it found them, asking LD A,I twice
# when the first answer is off (chapter 17, keep2). The programs of chapters 1
# to 18 print with the interrupts off and keep AT_PUTC, as photographed.
AT_ON = """
; at: B = row (0-23), C = column (0-31) -> the VDP's write address is that
;     cell of the name table, set with the interrupts off; then they are as
;     they were. Keeps BC, DE. Uses A, F, HL.
at:     push de
        ld l, b
        ld h, 0
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl
        add hl, hl              ; row x 32
        ld e, c
        ld d, $58               ; + $1800 + column, and bit 6 for a write
        add hl, de
        ld a, i                 ; P/V: the interrupts on or off (chapter 17)
        jp pe, .on
        ld a, i                 ; off, or one came just now: ask again
.on:    di
        ld a, l
        out (VDP_CTRL), a
        ld a, h
        out (VDP_CTRL), a       ; the two bytes, and nothing between them
        pop de
        ret po                  ; they were off: leave them off
        ei
        ret
""" + AT_PUTC[AT_PUTC.index("\n; putc:"):]


# ---------------------------------------------------------------- a handler that keeps its place
# The raster programs (ch01/beam_*, ch03/nops, ch04/edge) wait in `main: halt /
# jr main` and draw from an IM 2 handler. While halted the Z80 runs NOP after
# NOP, 5 T-states each on the MSX, and answers the interrupt only at the end of
# one, so up to 4 T-states late. Where in those 5 T-states the interrupt falls
# depends on where the last handler ended: if the round trip (answer, the JP at
# the vector, handler, JR) is not a whole number of 5-T steps short of a frame,
# the answer slips by the same amount every frame, and a stripe drawn by the
# handler walks back and forth over 4 T-states (6 pixels) with a period of
# five frames. steady() adds the LD A,(HL)s that make the round trip right,
# so that the stripe stands still; meas01 and meas03 check it over five frames.
T_MSX = {"nop": 5, "inc hl": 7, "ld a,(hl)": 8, "ei": 5, "ret": 11,     # Zilog + 1 per M1:
         "in a,(n)": 12, "out (c),r": 14, "jr main": 13, "halt": 5}     # chapter 3, timing.asm
IM2_ANSWER_T = 19       # IM 2: from the moment the interrupt is taken to the first
                        # instruction at the vector (chapter 17, measured: Zilog's 19)
IM2_JP_T = 11           # the JP at the vector, to the handler
FRAME_T_EU = 71364      # tools/meas.py: a frame of the European machine


def t_msx(line):
    """the MSX T-states of one line of a handler"""
    code = line.split(";")[0]
    if ":" in code:
        code = code.split(":", 1)[1]
    code = " ".join(code.replace(", ", ",").split()).lower()
    if code.startswith("out (c),"):
        code = "out (c),r"
    elif code.startswith("in a,(") and code != "in a,(c)":
        code = "in a,(n)"
    return T_MSX[code]


def steady(handler, frame_t=FRAME_T_EU):
    """the lines to put before the EI / RET that end `handler` (a list of lines,
    from the first instruction): k LD A,(HL) of 8 T-states, k from 0 to 4"""
    trip = IM2_ANSWER_T + IM2_JP_T + sum(t_msx(l) for l in handler if l.strip()) + \
        T_MSX["ei"] + T_MSX["ret"] + T_MSX["jr main"]
    # and the HALT's steps of 5 T-states, its own M1 among them, which change
    # nothing modulo 5. (Up to chapter 16 this read 20 for the answer and left
    # out the JP, adding the HALT's 5: the same modulo 5, and the same k.)
    k = 2 * ((frame_t - trip) % 5) % 5             # 8k = 3k (mod 5), and 3 x 2 = 1
    assert (trip + 8 * k - frame_t) % 5 == 0
    return ["        ld a,(hl)               ; keeps the stripes still: asmparts.steady"] * k


# ---------------------------------------------------------------- mode 2 (chapter 17)
# I is the page of a table of 257 bytes, all $C3. Whatever byte is on the bus,
# the two bytes read from the table are $C3 $C3, and every interrupt goes to
# $C3C3, which holds a jump to the routine. The table sits above VARS ($C100,
# the library's buffers) and far below the stack.
IM2_TABLE_AT = 0xC200
IM2_VECTOR = 0xC3C3
IM2 = f"""IM2_TABLE EQU ${IM2_TABLE_AT:04X}             ; 257 bytes of ${IM2_VECTOR >> 8:02X}: every vector is ${IM2_VECTOR:04X}
IM2_JUMP  EQU ${IM2_VECTOR:04X}             ; and there, a JP to the routine
"""


def im2(routine):
    """the lines that build the table and the jump in the RAM and switch
    mode 2 on, the interrupts still off (chapter 17)"""
    return f"""        ld hl, IM2_TABLE        ; mode 2: the table, 257 bytes of ${IM2_VECTOR >> 8:02X}
        ld de, IM2_TABLE + 1
        ld bc, 256
        ld (hl), high IM2_JUMP
        ldir
        ld a, $C3               ; and at ${IM2_VECTOR:04X}, JP {routine}
        ld (IM2_JUMP), a
        ld hl, {routine}
        ld (IM2_JUMP + 1), hl
        ld a, high IM2_TABLE
        ld i, a                 ; I: the page of the table
        im 2
"""
