"""asmparts.py - the pieces every generator builds its programs from.

When a book has a hundred programs, the fortieth copy of a routine pasted by
hand is not the same as the first. So the routines live here, once, as text,
and the chapter generators (chNN/genNN.py) put them together. Each routine
says which registers it takes and which it leaves alone.

The text routines draw on a Graphic I screen of 32 x 24 characters, with the
BIOS's own character set copied into the VDP and black ink on white paper,
which is what a page printed in black and white wants. They work with the
display switched off: a page is drawn, then shown, so that no write to the
VRAM ever comes too soon (chapter 20).
"""

