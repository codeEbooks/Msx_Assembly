#!/usr/bin/env python3
"""gen15.py - the programs of chapter 15, and the picture two of them load.

    python3 gen15.py && ./build.sh

    names.asm      chapter 8's five records printed with names: a constant,
                   a STRUCT, global and local labels; build.sh also writes
                   the symbol table, names.sym.
    exprs.asm      expressions the assembler works out (only the listing).
    fits.asm       numbers that do not fit, and 1B (only the listing, with
                   the assembler's warnings in it).
    macro.asm      HL = HL + n eight times, with a macro and with a
                   subroutine: bytes and T-states of each.
    rows.asm       chapter 13's two tables of line addresses, made by DUP at
                   assembly time and kept in the cartridge; ALIGN, ASSERT,
                   DISPLAY, and IFNDEF for sjasmplus -DUNALIGNED.
    picture.asm    a picture put into the cartridge with INCBIN and sent to
                   Graphic II's patterns as it is.
    rowwise.asm    the same picture, saved row after row.
    cart8.asm      a cartridge of 8 KB.
    cart32.asm     a cartridge of 32 KB, which reads its second half at INIT.
    big.asm        WHERE IT BREAKS: a cartridge one byte too long, with the
                   tail every cartridge of chapters 1 to 14 has.

    picture.bin    the picture: 6,144 bytes in the order of Graphic II's
                   patterns, eight lines of a cell, then the next cell.
    rowwise.bin    the same picture, the top line of 256 pixels first.

From this chapter on, cartridges end with asmparts.CART_END, whose ASSERT
comes before the padding, and build.sh assembles with --syntax=bFw: b and F as
since chapter 8, and w, which turns every warning into an error (this chapter
explains both).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "tools"))
from asmparts import (HEAD, TAIL, CART_END, TEXT_PAGE, SHOW_PAGE, GRAPHIC2,  # noqa: E402
                      library)

RESULTS = "RESULTS EQU RAM_START          ; what the program found: the debugger reads it here\n"


def head(name, what):
    return HEAD.format(name=name, chapter=15, what=what)


def listing_only(name, what):
    """the first lines of a source that writes no cartridge, only a listing"""
    return f"; {name}.asm -- chapter 15: {what}\n; generated by gen15.py\n"


# ---------------------------------------------------------------- names.asm
NAMES_ADDR = 0x1800         # the name table: one byte a cell (chapter 8)
RECORDS = [(3, 3, "2"), (5, 20, "'#'"), (9, 9, "'X'"), (13, 25, "'='"), (17, 5, "'O'")]


def names():
    recs = "".join(f"        obj {{NAMES+{r}*32+{c}, {ch}}}\n" for r, c, ch in RECORDS)
    return head("names", "chapter 8's records, with names") + f"""; Chapter 8's five records printed again, with names instead of numbers: a
; constant, a record's layout, global and local labels. None of the names is
; a byte of the program.
NAMES   EQU ${NAMES_ADDR:04X}               ; the name table: one byte a cell
OBJECTS EQU 5                   ; a constant: a number with a name
        STRUCT obj              ; a record's layout: offsets, not memory
cell    WORD                    ; obj.cell = 0: the first cell's address
char    BYTE                    ; obj.char = 2: its character
        ENDS                    ; obj = 3: the size of a record
""" + TEXT_PAGE + """start:  ld ix, objects
        ld b, OBJECTS
.next:  call paint              ; start.next
        ld de, obj
        add ix, de              ; IX to the next record
        djnz .next
        VDP_REG 1, $C0          ; display on: the page is finished
        jr $                    ; $: the address of this very line

; paint: the three cells of the record at IX. Uses A and C.
paint:  ld a, (ix+obj.cell)     ; the address: low byte ...
        out (VDP_CTRL), a
        ld a, (ix+obj.cell+1)   ; ... and high byte,
        or $40                  ; with bit 6 set: a write
        out (VDP_CTRL), a
        ld a, (ix+obj.char)
        ld c, 3
.next:  out (VDP_DATA), a       ; paint.next: not the same as start.next
        dec c
        jr nz, .next
        ret

objects:                        ; the same bytes as chapter 8's records
""" + recs + library() + CART_END


# ---------------------------------------------------------------- exprs.asm
# (expression, the table's note); meas15.py works each one out again in
# Python and compares
EXPRS = [
    ("dw 2+3*4", "* before +"),
    ("dw 1<<4+1", "+ before <<"),
    ("dw 100/7*7", "/ keeps no fraction"),
    ("dw -7/2", "and rounds towards 0"),
    ("dw -7%2", "the remainder has the sign of -7"),
    ("dw -16>>2", ">> keeps the sign"),
    ("dw -16>>>28", ">>> brings in zeros, over 32 bits"),
    ("db 3>2, 2>3", "true is -1, false is 0"),
    ("dw high $1234+1", "high before +"),
    ("dw high ($1234+1)", "unless in parentheses"),
    ("dw $F0 & $3C | 3", "& before |"),
    ("dw 7 <? 3, 7 >? 3", "the smaller, the larger"),
]

EXPRS_ASM = listing_only("exprs", "numbers the assembler works out") + """; There is no program here: build.sh writes only the listing, which shows
; what each line became. Chapter 15 has a table of them, with the rule each
; one follows.
        ORG $4000
""" + "".join(f"        {e}\n" for e, c in EXPRS)

# ----------------------------------------------------------------- fits.asm
FITS = listing_only("fits", "numbers that do not fit") + """; Numbers that do not fit, and a label that is a number. There is no
; program here: build.sh writes only the listing, warnings and all.
        ORG $4000
        ld a,256                ; 256 needs nine bits
        ld a,-200               ; -200 does not fit in a byte either
        db 300
        dw 70000
1       nop                     ; a temporary label: a number
        ld hl,1_B               ; the label 1, back up the source
        ld hl,1B                ; the number 1, in binary
        jr 1B                   ; in a jump, 1B is the label
"""

# ---------------------------------------------------------------- macro.asm
MACRO_N = [10 * k + 5 for k in range(8)]


def macro():
    return head("macro", "a macro and a subroutine") + RESULTS + """; HL = HL + n eight times with a macro, and eight times with a subroutine:
; the same sum, and the bytes and T-states of each way.

        MACRO ADDHL n           ; HL = HL + n, n from 0 to 255; A is lost
        ld a, n
        add a, l
        ld l, a
        adc a, h
        sub l
        ld h, a
        ENDM

; addhla: HL = HL + A, the same five instructions once. A is lost.
addhla: add a, l
        ld l, a
        adc a, h
        sub l
        ld h, a
        ret

init:   di
        ld sp, SYS_AREA
        ld hl, 0
m0:     DUP 8, k                ; k = 0, 1 ... 7
        ADDHL 10*k+5            ; the macro: six instructions every time
        EDUP
m1:     ld (RESULTS), hl
        ld hl, 0
m2:     DUP 8, k
        ld a, 10*k+5
        call addhla             ; the subroutine: two instructions every time
        EDUP
m3:     ld (RESULTS+2), hl
stop:   jr stop
""" + CART_END


# ----------------------------------------------------------------- rows.asm
PATTERNS = 0x0000           # Graphic II's patterns (chapter 13)


def line_addr(y):
    """the address in Graphic II's patterns of pixel line y, at the left
    edge: the row of cells times 256, and the line in the cell (chapter 13)"""
    return PATTERNS + (y >> 3) * 256 + (y & 7)


def rows():
    return head("rows", "chapter 13's tables, made by the assembler") + f"""; Chapter 13's two tables of line addresses, made by the assembler instead
; of at run time: they are in the cartridge, and the program spends no time
; on them. ASSERT and DISPLAY check them as it assembles.
PATTERNS EQU ${PATTERNS:04X}              ; Graphic II's patterns (chapter 13)
init:   di
        ld sp, SYS_AREA
        ld a, 100
        call line               ; HL: the address of pixel line 100
stop:   jr stop

; line: HL = the address of pixel line A (0-191), from the tables
line:   ld l, a
        ld h, high lines
        ld a, (hl)              ; the low byte
        inc h
        ld h, (hl)              ; the high byte, a page on
        ld l, a
        ret

        IFNDEF UNALIGNED        ; sjasmplus -DUNALIGNED leaves this out
        ALIGN 256               ; on to the start of the next page
        ENDIF
lines:  DUP 192, y              ; y = 0, 1 ... 191: a low byte each
adr = PATTERNS + (y >> 3) * 256 + (y & 7)
        db low adr
        EDUP
        ALIGN 256
highs:  DUP 192, y              ; the high bytes, a page on
adr = PATTERNS + (y >> 3) * 256 + (y & 7)
        db high adr
        EDUP
        ASSERT low lines == 0, not on a page
        DISPLAY "lines ",/H,lines,", high bytes ",/H,highs,", end ",/H,$
""" + CART_END


# ------------------------------------------------------ picture.asm, rowwise
def picture_asm(name, what, comment):
    return head(name, what) + comment + GRAPHIC2 + f"""        VDP_REG 7, LIGHT_GREEN  ; the border: where the picture ends shows
        VRAM_WRITE $0000        ; the patterns, from the first
        ld hl, picture
        ld c, VDP_DATA
        ld d, 24                ; 24 times 256 bytes
        ld b, 0
p1:     otir                    ; 256 bytes to the VDP (chapter 13)
        dec d
        jr nz, p1
""" + SHOW_PAGE + f"""
picture:
{'        INCBIN "' + name + '.bin"':<32}; 6,144 bytes, as they are in the file
""" + CART_END


PICTURE = picture_asm("picture", "a picture, with INCBIN", """; A picture put into the cartridge by the assembler, and sent to Graphic
; II's patterns as it is, with the display off (chapter 13).
""")
ROWWISE = picture_asm("rowwise", "the same picture, row after row", """; The same picture, saved the way most programs save one: the top line of
; 256 pixels first, then the next, down to the bottom; sent the same way.
""")

# the picture: in the left eight columns of cells, all ink, the numbers of
# the screen's three thirds, one in each, in paper; on the right, a ring
DIGITS = {
    "1": ["..#..", ".##..", "#.#..", "..#..", "..#..", "..#..", "#####"],
    "2": [".###.", "#...#", "....#", "...#.", "..#..", ".#...", "#####"],
    "3": ["####.", "....#", "....#", ".###.", "....#", "....#", "####."],
}
STRIP = 8                   # columns of cells on the left, all ink
RING = (160, 96, 72, 88)    # centre x, y, inner and outer radius


def ink(x, y):
    """is pixel (x, y) of the picture ink?"""
    if x < 8 * STRIP:
        third, top = y // 64, y % 64 - 4
        if 12 <= x < 52 and 0 <= top < 56:
            return DIGITS["123"[third]][top // 8][(x - 12) // 8] != "#"
        return True
    cx, cy, r0, r1 = RING
    return r0 * r0 <= (x - cx) ** 2 + (y - cy) ** 2 < r1 * r1


def byte_at(col, y):
    """the byte of the picture for cell column col on pixel line y"""
    return sum(ink(8 * col + b, y) << (7 - b) for b in range(8))


def pattern_offset(col, y):
    """where Graphic II keeps the byte for cell column col, line y"""
    return (y >> 3) * 256 + col * 8 + (y & 7)


def picture_bin():
    out = bytearray(6144)
    for y in range(192):
        for col in range(32):
            out[pattern_offset(col, y)] = byte_at(col, y)
    return bytes(out)


def rowwise_bin():
    return bytes(byte_at(col, y) for y in range(192) for col in range(32))


# ------------------------------------------------------- cart8.asm, cart32.asm
def cart8():
    return head("cart8", "a cartridge of 8 KB") + """; A cartridge of 8 KB, the size of many early MSX games: the same header,
; and the padding stops at $6000.
init:   di
        ld sp, SYS_AREA
        VDP_REG 7, LIGHT_GREEN  ; the border light green: it runs
stop:   jr stop
        ASSERT $ <= $6000, the program is longer than 8 KB
        ds $6000 - $, $FF       ; pad the cartridge to 8 KB
"""


SECOND = "The second half."


def cart32():
    return head("cart32", "a cartridge of 32 KB") + RESULTS + f"""; A cartridge of 32 KB: the second 16 KB is for page 2, $8000-$BFFF. At
; INIT the BIOS has switched page 1 to the cartridge, and only page 1
; (chapter 3): the program reads the first byte of its second half.
init:   di
        ld sp, SYS_AREA
        ld a, (second)          ; the first byte of the second half ...
        ld (RESULTS), a         ; ... as the processor finds it
        VDP_REG 7, LIGHT_GREEN
stop:   jr stop
        ASSERT $ <= $8000, the first half is full
        ds $8000 - $, $FF       ; the first 16 KB
second: db "{SECOND}"
        ASSERT $ <= $C000, the program is longer than the cartridge
        ds $C000 - $, $FF       ; the second 16 KB
"""


# ------------------------------------------------------------------ big.asm
def big():
    # the first line: verify.py compares the cartridge it writes, and it is
    # a cartridge; the trap is how it was written, not that it fails
    return head("big", "WHERE IT BREAKS: one byte too many") + """; WHERE IT BREAKS. A program that has grown one byte past its 16 KB, with
; the tail of every cartridge in chapters 1 to 14: the ds after it is
; negative, and the ASSERT after the ds is satisfied all the same.
init:   di
        ld sp, SYS_AREA
        call last               ; a routine at the very end of the page
        VDP_REG 7, LIGHT_GREEN  ; back from it: the border light green
stop:   jr stop
        ds $7FFF - $, 0         ; the rest of a program that has grown
last:   nop                     ; at $7FFF ...
        ret                     ; ... and RET at $8000: one byte too many
""" + TAIL


def main():
    files = {"names.asm": names(), "exprs.asm": EXPRS_ASM, "fits.asm": FITS,
             "macro.asm": macro(), "rows.asm": rows(), "picture.asm": PICTURE,
             "rowwise.asm": ROWWISE, "cart8.asm": cart8(), "cart32.asm": cart32(),
             "big.asm": big()}
    for name, text in files.items():
        with open(os.path.join(HERE, name), "w") as f:
            f.write("\n".join(l.rstrip() for l in text.split("\n")))    # no spaces at line ends
    for name, data in (("picture.bin", picture_bin()), ("rowwise.bin", rowwise_bin())):
        assert len(data) == 6144
        with open(os.path.join(HERE, name), "wb") as f:
            f.write(data)
    print(len(files), "sources and 2 pictures written")


if __name__ == "__main__":
    main()
